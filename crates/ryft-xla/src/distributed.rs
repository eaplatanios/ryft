//! High-level distributed runtime setup for `ryft-xla`.
//!
//! [`DistributedRuntime`] is the `ryft` analogue of `jax.distributed.initialize`. It composes
//! [`ryft_pjrt::Plugin::distributed_runtime_service`], [`ryft_pjrt::Plugin::distributed_runtime_client`], and
//! [`ryft_pjrt::DistributedKeyValueStore`] into a single entry point. The handle owns the coordinator service, on the
//! elected coordinator node only, and the per-process distributed runtime client. Subsequent [`ryft_pjrt::Client`]
//! construction routes through the bundled key-value store, so PJRT cross-host primitives have the rendezvous surface
//! they need.
//!
//! ## Usage
//!
//! Each participating process calls [`DistributedRuntime::initialize`] with identical `coordinator_address` and
//! `node_count` values but a unique `node_id`, where 0 designates the coordinator. The call blocks until every node has
//! joined. After that, use [`DistributedRuntime::create_client`] to mint a PJRT [`ryft_pjrt::Client`] that
//! participates in cross-host transfers and SPMD compilation.
//!
//! Initialization also establishes a launch identity generated by the coordinator. Rendezvous keys of compilation
//! artifacts are scoped to that identity, so a later job cannot observe terminal records or chunks from an earlier
//! launch.
//!
//! Drop order matters. Keep the [`DistributedRuntime`] alive at least as long as the [`ryft_pjrt::Client`] it
//! produced, because the client borrows the runtime's key-value store.

