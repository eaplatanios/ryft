    #[test]
    fn test_operation_parser_rejects_invalid_variant_classes() {
        let cases = [
            (
                quote!(#[ryft(projected(ArrayType), projected(ArrayType))]),
                "duplicate ryft operation variant class 'projected'",
            ),
            (quote!(#[ryft(mixed(ArrayType), mixed(ArrayType))]), "duplicate ryft operation variant class 'mixed'"),
            (
                quote!(#[ryft(projected(ArrayType), mixed(ArrayType))]),
                "contradictory ryft operation variant classes 'projected' and 'mixed'",
            ),
            (quote!(#[ryft(projected)]), "expected parentheses"),
            (
                quote!(#[ryft(mixed)]),
                "the 'mixed' operation variant class cannot default its member type because the operation family \
                 declares no '#[ryft(members(...))]'; declare the family's members or name the member type as \
                 'mixed(U)'",
            ),
            (
                quote!(#[ryft(projected(ArrayType, replicated))]),
                "invalid projected operation variant role 'replicated'; only 'structural' is supported here",
            ),
            (
                quote!(#[ryft(mixed(ArrayType, replicated))]),
                "invalid mixed operation variant role 'replicated'; only 'structural' is supported here",
            ),
            (
                quote!(#[ryft(projected(ArrayType, structural, DimensionType))]),
                "the 'projected' operation variant class accepts one member type and an optional role",
            ),
            (
                quote!(#[ryft(mixed(ArrayType, structural, DimensionType))]),
                "the 'mixed' operation variant class accepts one member type and an optional role",
            ),
            (quote!(#[ryft(skip_from, skip_from)]), "duplicate ryft operation variant attribute 'skip_from'"),
            (
                quote!(#[ryft(structural(DimensionType))]),
                "the 'structural' operation variant class was replaced by the 'projected(U, structural)' role form",
            ),
            (
                quote!(#[ryft(composite_member(ArrayType))]),
                "invalid operation variant '#[ryft(...)]' attribute: 'composite_member'; only 'projected', 'mixed', \
                 and 'skip_from' are supported here",
            ),
        ];
        for (attribute, expected_error) in cases {
            let mut generator = OperationParser::new();
            let input = syn::parse2(quote! {
                enum Operation<V: Value<Type = DataType>> {
                    #attribute
                    Member(MemberOperation<V>),
                }
            })
            .expect("failed to parse derive input");
            assert_eq!(generator.extract_variants(&input).len(), 1);
            let errors = generator.errors.iter().map(syn::Error::to_string).collect::<Vec<_>>();
            assert!(errors.iter().any(|error| error.contains(expected_error)), "errors: {errors:?}");
        }
    }

    #[test]
    fn test_operation_parser_defaults_mixed_member_types_from_declared_members() {
        /// Extracts the variants of a derive input whose enum-level attributes have already been parsed, which is the
        /// order the derive entry point uses and the order that makes declared members available to variant markers.
        fn extract_variants(tokens: TokenStream) -> (OperationParser, Vec<OperationVariant>) {
            let mut input = syn::parse2(tokens).expect("failed to parse derive input");
            replace_self_type(&mut input);
            let mut parser = OperationParser::new();
            parser.extract_attributes(&input);
            let variants = parser.extract_variants(&input);
            (parser, variants)
        }

        // With one declared computational member universe, both abbreviated mixed forms take their data universe from
        // the declaration while the explicit forms keep naming it.
        let (parser, variants) = extract_variants(quote! {
            #[ryft(type = ArrayIrType, constant = ArrayIrValue<A>)]
            #[ryft(members(ArrayType, structural(DimensionType)))]
            enum Operation<A: Value<Type = ArrayType>> {
                #[ryft(mixed)]
                Mixed(AllGatherOperation),
                #[ryft(mixed(structural))]
                MixedStructural(ZeroOperation<ArrayType>),
                #[ryft(mixed(ArrayType))]
                ExplicitMixed(AllToAllOperation),
                #[ryft(projected(DimensionType, structural))]
                Dimension(DimensionOperation),
            }
        });
        assert!(
            parser.errors.is_empty(),
            "errors: {:?}",
            parser.errors.iter().map(syn::Error::to_string).collect::<Vec<_>>()
        );
        let classes = variants
            .iter()
            .map(|variant| match &variant.class {
                OperationVariantClass::MixedMember { member_type, structural } => {
                    ("mixed", member_type.to_token_stream().to_string(), *structural)
                }
                OperationVariantClass::ProjectedMember { member_type, structural } => {
                    ("projected", member_type.to_token_stream().to_string(), *structural)
                }
                OperationVariantClass::CompositeNative => ("native", String::new(), false),
            })
            .collect::<Vec<_>>();
        assert_eq!(
            classes,
            vec![
                ("mixed", "ArrayType".to_string(), false),
                ("mixed", "ArrayType".to_string(), true),
                ("mixed", "ArrayType".to_string(), false),
                ("projected", "DimensionType".to_string(), true),
            ],
        );

        // A member marker naming a type the family does not declare is a declaration mismatch rather than a silent
        // second member universe.
        let (parser, _) = extract_variants(quote! {
            #[ryft(type = ArrayIrType, constant = ArrayIrValue<A>)]
            #[ryft(members(ArrayType))]
            enum Operation<A: Value<Type = ArrayType>> {
                #[ryft(mixed(DimensionType))]
                Mixed(AllGatherOperation),
            }
        });
        assert_eq!(
            parser.errors.iter().map(syn::Error::to_string).collect::<Vec<_>>(),
            vec![
                "the 'mixed' operation variant class declares member type 'DimensionType', which the operation family \
                 does not declare in '#[ryft(members(...))]'"
                    .to_string(),
            ],
        );

        // Several computational member universes leave the data universe ambiguous, so the abbreviated forms are
        // rejected in favor of the explicit one.
        let (parser, _) = extract_variants(quote! {
            #[ryft(type = ArrayIrType, constant = ArrayIrValue<A>)]
            #[ryft(members(ArrayType, DimensionType))]
            enum Operation<A: Value<Type = ArrayType>> {
                #[ryft(mixed)]
                Mixed(AllGatherOperation),
            }
        });
        assert_eq!(
            parser.errors.iter().map(syn::Error::to_string).collect::<Vec<_>>(),
            vec![
                "the 'mixed' operation variant class cannot default its member type because the operation family \
                 declares 2 computational member universes; name the member type as 'mixed(U)'"
                    .to_string(),
            ],
        );
    }

