    #[test]
    fn test_operation_generates_composite_member_dispatchers() {
        let mut input: syn::DeriveInput = syn::parse_quote! {
            #[ryft(type = ArrayIrType, constant = ArrayIrValue<A>)]
            #[ryft(dispatch(batching, differentiation, transposition))]
            enum CompositeOperation<A: Value<Type = ArrayType>> {
                #[ryft(projected(ArrayType))]
                Array(ArrayOperation<A>),
                #[ryft(projected(DimensionType, structural))]
                Dimension(DimensionOperation),
                #[ryft(mixed(ArrayType))]
                Collective(AllGatherOperation),
                #[ryft(mixed(ArrayType, structural))]
                DynamicZero(ZeroOperation<ArrayType>),
                Native(NativeOperation<ArrayIrType>),
            }
        };
        replace_self_type(&mut input);

        let mut parser = OperationParser::new();
        parser.extract_attributes(&input);
        let operation = parser.normalize_input(&input).expect("failed to normalize composite operation enum");
        let generated_tokens = operation.generate().to_string();
        let generated = generated_tokens.replace(' ', "");

        // Both projected roles share projection-based base and batching dispatch, while their differentiation and
        // transposition contracts remain intentionally distinct.
        assert!(generated.contains("infer_projected_operation_output_types(operation,input_types,region_interfaces,)"));
        assert!(generated.contains("batch_projected_operation(context,operation,inputs)"));
        assert!(generated.contains("OperationProjection<ArrayType>forCompositeOperation<A>"));
        assert!(generated.contains("OperationProjection<DimensionType>forCompositeOperation<A>"));
        assert!(generated.contains("jvp_in_parent(operation,context,driver,inputs)"));
        assert!(generated.contains("DifferentiationDual::new_with_zero_tangent"));
        assert!(generated.contains("transpose_projected_operation(context,operation,inputs,outputs)"));
        assert!(generated.contains("MaybeZero::Zero(input.r#type().cotangent()?)"));

        // Mixed payloads use their parent-universe contracts, while native payloads continue to delegate directly.
        assert!(generated.contains("MemberOperation<ArrayIrType>>::infer_parent_output_types"));
        assert!(generated.contains("MemberInterpretableOperation<__Context>>::interpret_in_parent"));
        assert!(generated.contains("MemberBatchableOperation<__ParentContext,__BatchingPolicy,>>::batch_in_parent"));
        assert!(generated.contains("MemberDifferentiableOperation<__DifferentiationContext>>::jvp_in_parent"));
        assert!(generated.contains("transpose_mixed_operation(context,operation,inputs,outputs)"));
        assert!(generated.contains("NativeOperation<ArrayIrType>asryft::Operation>::infer_output_types"));

        // The structural mixed role keeps the shared mixed base, interpretation, batching, and transposition dispatch
        // while replacing only the forward-mode arm with a generated primal plus member zero tangent over the same
        // parent-universe operands.
        assert!(generated.contains("ryft::ZeroOperation<ArrayType>,>>::from(ryft::ZeroOperation::new(tangent_type))"));
        assert!(generated.contains("Self::DynamicZero(operation)=>{letprimal_inputs"));

        // Borrowed payload projections report a canonical type error naming the projected operation and the statically
        // expected payload type.
        assert!(generated.contains("typeError=ryft::TypeError;"));
        assert!(generated_tokens.contains(r#""cannot project operation '{}' into a '{}' payload""#));
        assert!(generated_tokens.contains(r#""ArrayOperation<A>""#));
    }

    #[test]
    fn test_operation_generates_declared_member_mixed_dispatchers() {
        /// Generates the derive output for one enum whose attributes are parsed exactly like the derive entry point
        /// parses them.
        fn generate(tokens: TokenStream) -> String {
            let mut input: syn::DeriveInput = syn::parse2(tokens).expect("failed to parse derive input");
            replace_self_type(&mut input);
            let mut parser = OperationParser::new();
            parser.extract_attributes(&input);
            let operation = parser.normalize_input(&input).expect("failed to normalize operation enum");
            assert!(
                parser.errors.is_empty(),
                "errors: {:?}",
                parser.errors.iter().map(syn::Error::to_string).collect::<Vec<_>>()
            );
            operation.generate().to_string()
        }

        // Declaring the family's members and abbreviating both mixed markers generates exactly the same code as naming
        // the data universe on every marker, so declaring members is a pure notation change for a family with one
        // computational member universe.
        let explicit = generate(quote! {
            #[ryft(type = ArrayIrType, constant = ArrayIrValue<A>)]
            #[ryft(dispatch(batching, differentiation, transposition))]
            enum CompositeOperation<A: Value<Type = ArrayType>> {
                #[ryft(mixed(ArrayType))]
                Collective(AllGatherOperation),
                #[ryft(mixed(ArrayType, structural))]
                DynamicZero(ZeroOperation<ArrayType>),
                #[ryft(projected(ArrayType))]
                Array(ArrayOperation<A>),
                #[ryft(projected(DimensionType, structural))]
                Dimension(DimensionOperation),
            }
        });
        let declared = generate(quote! {
            #[ryft(type = ArrayIrType, constant = ArrayIrValue<A>)]
            #[ryft(members(ArrayType, structural(DimensionType)))]
            #[ryft(dispatch(batching, differentiation, transposition))]
            enum CompositeOperation<A: Value<Type = ArrayType>> {
                #[ryft(mixed)]
                Collective(AllGatherOperation),
                #[ryft(mixed(structural))]
                DynamicZero(ZeroOperation<ArrayType>),
                #[ryft(projected(ArrayType))]
                Array(ArrayOperation<A>),
                #[ryft(projected(DimensionType, structural))]
                Dimension(DimensionOperation),
            }
        });
        assert_eq!(declared, explicit);

        // A structural mixed payload's zero tangent is selected per output universe: one staged member zero constructor
        // per declared computational member universe, and a symbolic zero tangent for an output outside all of them.
        let generated = generate(quote! {
            #[ryft(type = CompositeType, constant = CompositeValue<A>)]
            #[ryft(members(ArrayType, TableType, structural(DimensionType)))]
            #[ryft(dispatch(differentiation))]
            enum MultipleMemberOperation<A: Value<Type = ArrayType>> {
                #[ryft(mixed(ArrayType, structural))]
                DynamicZero(ZeroOperation<ArrayType>),
                #[ryft(projected(ArrayType))]
                Array(ArrayOperation<A>),
            }
        })
        .replace(' ', "");
        assert!(generated.contains("ryft::ZeroOperation<ArrayType>,>>::from(ryft::ZeroOperation::new(tangent_type))"));
        assert!(generated.contains("ryft::ZeroOperation<TableType>,>>::from(ryft::ZeroOperation::new(tangent_type))"));
        assert!(generated.contains("ryft::DifferentiationDual::new_with_zero_tangent(primal)"));
        assert!(generated.contains("TableType:ryft::DifferentiableType"));
        assert!(!generated.contains("ryft::ZeroOperation<DimensionType>"));
    }

