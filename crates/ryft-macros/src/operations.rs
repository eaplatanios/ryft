const RYFT_ATTRIBUTE: Symbol = Symbol::new("ryft");
const CRATE_ATTRIBUTE: Symbol = Symbol::new("crate");
const DISPATCH_ATTRIBUTE: Symbol = Symbol::new("dispatch");
const TYPE_ATTRIBUTE: Symbol = Symbol::new("type");
const CONSTANT_ATTRIBUTE: Symbol = Symbol::new("constant");
const MEMBERS_ATTRIBUTE: Symbol = Symbol::new("members");
const BATCHING_ATTRIBUTE: Symbol = Symbol::new("batching");
const DIFFERENTIATION_ATTRIBUTE: Symbol = Symbol::new("differentiation");
const TRANSPOSITION_ATTRIBUTE: Symbol = Symbol::new("transposition");
const PROJECTED_ATTRIBUTE: Symbol = Symbol::new("projected");
const STRUCTURAL_ATTRIBUTE: Symbol = Symbol::new("structural");
const MIXED_ATTRIBUTE: Symbol = Symbol::new("mixed");
const SKIP_FROM_ATTRIBUTE: Symbol = Symbol::new("skip_from");
const VALID_CONTAINER_ATTRIBUTES: [Symbol; 5] =
    [CRATE_ATTRIBUTE, DISPATCH_ATTRIBUTE, TYPE_ATTRIBUTE, CONSTANT_ATTRIBUTE, MEMBERS_ATTRIBUTE];

const DEFAULT_RYFT_CRATE: Symbol = Symbol::new("ryft");
/// Mutable parser and diagnostic accumulator for `#[derive(Operation)]`.
struct OperationParser {
    /// Path to the `ryft` crate or facade used by generated code.
    ryft_crate: syn::Path,

    /// Type descriptor for the generated [`Operation`](ryft_core::Operation) implementation.
    operation_type: Option<syn::Type>,

    /// Explicit stored constant type for a composite operation family, when declared with `#[ryft(constant = V)]`.
    program_constant_type: Option<syn::Type>,

    /// Member universes declared with `#[ryft(members(...))]`, in declaration order. Empty when the enum declares no
    /// member universes, in which case every member variant must name its own member type.
    members: Vec<OperationMember>,

    /// Optional operation dispatchers selected through `#[ryft(dispatch(...))]`.
    dispatchers: Option<Dispatchers>,

    /// Errors accumulated in this [`OperationParser`]. The way error handling works in this parser is that we
    /// collect errors as we encounter them, and keep going as far as we can with the information that is available,
    /// before raising them. That is meant to enable a smoother development experience when working with `ryft` by
    /// reducing the amount of trial and error required to get something work (i.e., users do not need to keep trying,
    /// fixing one error at a time; they get to see multiple errors at once, when there are multiple).
    errors: Vec<syn::Error>,
}

/// One member universe of an operation family, declared through the enum-level `#[ryft(members(...))]` attribute as
/// either a bare type (a computational member) or `structural(Type)` (a structural member).
#[derive(Clone)]
struct OperationMember {
    /// [`Type`](ryft_core::Type) of this member universe.
    r#type: syn::Type,

    /// Whether this member universe is structural, meaning that its values are bookkeeping with a zero differential
    /// space rather than differentiable data.
    structural: bool,
}

/// Optional dispatchers generated by `#[derive(Operation)]`.
#[derive(Copy, Clone, Default)]
struct Dispatchers {
    /// Whether to generate the batching dispatcher.
    batching: bool,

    /// Whether to generate the differentiation dispatcher.
    differentiation: bool,

    /// Whether to generate the transposition dispatcher.
    transposition: bool,
}

/// Normalized operation enum shared by every generated dispatcher.
struct OperationEnum {
    /// Path to the `ryft` crate or facade used by generated code.
    ryft_crate: syn::Path,

    /// Type descriptor for the generated [`Operation`](ryft_core::Operation) implementation.
    operation_type: syn::Type,

    /// Member universes declared with `#[ryft(members(...))]`, in declaration order.
    members: Vec<OperationMember>,

    /// Optional operation dispatchers selected through `#[ryft(dispatch(...))]`.
    dispatchers: Dispatchers,

    /// Enum identifier.
    ident: syn::Ident,

    /// Original enum generics after recursive `Self` replacement.
    generics: syn::Generics,

    /// Enum generics without defaults, used by conversion implementations.
    conversion_generics: syn::Generics,

    /// Enum generics with generic-extension operation bounds, used by semantic implementations.
    operation_generics: syn::Generics,

    /// Enum self type using all declared generic arguments.
    self_type: syn::Type,

    /// Whether semantic implementations use a runtime value type distinct from the stored program constant type.
    has_separate_runtime_value_type: bool,

    /// Stored constant type of programs whose operation family is this enum.
    program_constant_type: syn::Type,

    /// Generic value parameter whose capability bounds should be copied to a distinct runtime value type. Explicit
    /// composite constant types have no one-to-one generic source and therefore store [`None`].
    program_constant_parameter: Option<syn::Ident>,

    /// Program-shaped generics after reducing payload-specific value parameters to the program constant space.
    program_generics: syn::Generics,

    /// Program-shaped enum self type after reducing payload-specific value parameters to the program constant space.
    program_self_type: syn::Type,

    /// Normalized operation variants.
    variants: Vec<OperationVariant>,
}

/// Generates the `#[derive(Operation)]` expansion for `input`.
pub(crate) fn generate_operation_impl(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    let mut input = syn::parse_macro_input!(input as syn::DeriveInput);
    replace_self_type(&mut input);

    let mut parser = OperationParser::new();
    parser.extract_attributes(&input);
    if parser.has_errors() {
        return parser.into_compile_error().into();
    }

    let Some(operation_enum) = parser.normalize_input(&input) else {
        return parser.into_compile_error().into();
    };
    operation_enum.generate().into()
}

impl OperationParser {
    /// Creates a new [`OperationParser`] with default parser state.
    fn new() -> Self {
        OperationParser {
            ryft_crate: DEFAULT_RYFT_CRATE.into(),
            operation_type: None,
            program_constant_type: None,
            members: Vec::new(),
            dispatchers: None,
            errors: Vec::new(),
        }
    }

    /// Adds an error to this [`OperationParser`] with the specified message spanning the provided tokens. This is only
    /// meant to be used internally by this class as a convenient helper for collecting errors.
    ///
    /// # Parameters
    ///
    ///   - `tokens`: Tokens that the error spans.
    ///   - `message`: Message describing the error.
    fn add_error<T: ToTokens, U: Display>(&mut self, tokens: T, message: U) {
        self.errors.push(syn::Error::new_spanned(tokens.into_token_stream(), message));
    }

    /// Returns whether any diagnostics have been accumulated.
    fn has_errors(&self) -> bool {
        !self.errors.is_empty()
    }

    /// Combines all accumulated diagnostics into one `compile_error!` token stream.
    ///
    /// This method is called only after [`OperationParser::has_errors`] returns `true` or normalization returns
    /// [`None`], which always adds at least one diagnostic.
    fn into_compile_error(self) -> TokenStream {
        let mut errors = self.errors.into_iter();
        let mut error = errors.next().unwrap();
        for next_error in errors {
            error.combine(next_error);
        }
        error.into_compile_error()
    }

    /// Extracts any `#[ryft(...)]` attributes that are attached to the provided [`syn::DeriveInput`] and checks for
    /// unknown top-level (i.e., not field or variant) `#[ryft(...)]` attributes. This function will set
    /// [`OperationParser::ryft_crate`], [`OperationParser::members`], and [`OperationParser::dispatchers`] if it is
    /// able to successfully extract them. By default it infers [`OperationParser::operation_type`] from the enum's
    /// unique `Value<Type = T>` generic bound. Composite enums whose generic values belong to member universes instead
    /// declare their outer operation and stored constant types together with `#[ryft(type = T, constant = V)]`.
    fn extract_attributes(&mut self, input: &syn::DeriveInput) {
        let mut ryft_crate = Attribute::new(CRATE_ATTRIBUTE);
        let mut operation_type = Attribute::new(TYPE_ATTRIBUTE);
        let mut program_constant_type = Attribute::new(CONSTANT_ATTRIBUTE);
        input.attrs.iter().filter(|attr| attr.path() == &RYFT_ATTRIBUTE).for_each(|attr| {
            attr.parse_nested_meta(|meta| match &meta.path {
                path if path == &CRATE_ATTRIBUTE => ryft_crate.set(&meta),
                path if path == &DISPATCH_ATTRIBUTE => self.extract_dispatch_attribute(&meta),
                path if path == &MEMBERS_ATTRIBUTE => self.extract_members_attribute(&meta),
                path if path == &TYPE_ATTRIBUTE => operation_type.set(&meta),
                path if path == &CONSTANT_ATTRIBUTE => program_constant_type.set(&meta),
                _ => Err(meta.error(format_args!(
                    "invalid '#[ryft(...)]' attribute: '{}'; these are the attributes that are supported here: {:?}",
                    meta.path.to_token_stream().to_string().replace(' ', ""),
                    VALID_CONTAINER_ATTRIBUTES,
                ))),
            })
            .unwrap_or_else(|error| self.errors.push(error));
        });

        if let Some(ryft_crate) = ryft_crate.get() {
            self.ryft_crate = ryft_crate;
        }
        match (operation_type.get(), program_constant_type.get()) {
            (Some(operation_type), Some(program_constant_type)) => {
                self.operation_type = Some(operation_type);
                self.program_constant_type = Some(program_constant_type);
            }
            (None, None) => {
                let inferred_types = unique_value_bound_arguments(&input.generics);
                match inferred_types.as_slice() {
                    [operation_type] => self.operation_type = Some(operation_type.clone()),
                    [] => self.add_error(
                        &input.ident,
                        "could not infer an operation type because no generic parameter is bounded by 'Value<Type = T>'",
                    ),
                    _ => self.add_error(
                        &input.generics,
                        "could not infer a unique operation type because multiple distinct 'Value<Type = T>' bounds are present",
                    ),
                }
            }
            _ => self.add_error(
                &input.ident,
                "explicit operation-family declarations must specify both 'type' and 'constant'",
            ),
        }
    }

    /// Extracts the optional dispatchers selected by a `#[ryft(dispatch(...))]` attribute.
    fn extract_dispatch_attribute(&mut self, meta: &syn::meta::ParseNestedMeta) -> syn::Result<()> {
        if self.dispatchers.is_some() {
            return Err(meta.error("duplicate ryft attribute 'dispatch(...)'"));
        }

        let content;
        syn::parenthesized!(content in meta.input);
        if content.is_empty() {
            return Err(content.error("'#[ryft(dispatch(...))]' must select at least one dispatcher"));
        }
        let dispatchers = syn::punctuated::Punctuated::<syn::Path, syn::Token![,]>::parse_terminated(&content)?;
        let mut selected_dispatchers = Dispatchers::default();
        for dispatcher in dispatchers {
            let selected = match &dispatcher {
                path if path == &BATCHING_ATTRIBUTE => &mut selected_dispatchers.batching,
                path if path == &DIFFERENTIATION_ATTRIBUTE => &mut selected_dispatchers.differentiation,
                path if path == &TRANSPOSITION_ATTRIBUTE => &mut selected_dispatchers.transposition,
                _ => {
                    return Err(syn::Error::new_spanned(
                        &dispatcher,
                        format_args!(
                            "invalid '#[ryft(dispatch(...))]' dispatcher: '{}'; only 'batching', 'differentiation', and \
                         'transposition' are supported here",
                            dispatcher.to_token_stream().to_string().replace(' ', ""),
                        ),
                    ));
                }
            };
            if *selected {
                return Err(syn::Error::new_spanned(
                    &dispatcher,
                    format_args!(
                        "duplicate ryft dispatcher '{}'",
                        dispatcher.to_token_stream().to_string().replace(' ', ""),
                    ),
                ));
            }
            *selected = true;
        }
        self.dispatchers = Some(selected_dispatchers);
        Ok(())
    }

    /// Extracts the member universes declared by a `#[ryft(members(...))]` attribute. Each entry is either a bare
    /// [`Type`](ryft_core::Type) naming a computational member or `structural(Type)` naming a structural member.
    /// Declaring the family's members lets variant markers default their data universe (`mixed` and
    /// `mixed(structural)`), lets member markers be cross-checked against the family, and gives the generated
    /// structural forward-mode arm the literal member types it needs to classify each output universe.
    fn extract_members_attribute(&mut self, meta: &syn::meta::ParseNestedMeta) -> syn::Result<()> {
        if !self.members.is_empty() {
            return Err(meta.error("duplicate ryft attribute 'members(...)'"));
        }

        let content;
        syn::parenthesized!(content in meta.input);
        if content.is_empty() {
            return Err(content.error("'#[ryft(members(...))]' must declare at least one member universe"));
        }
        let mut members = Vec::<OperationMember>::new();
        while !content.is_empty() {
            // A leading identifier followed by parentheses declares the role of the member type inside those
            // parentheses. Any other entry is the member type itself.
            let role = content.fork();
            let declared_role = role.parse::<syn::Ident>().ok().filter(|_| role.peek(syn::token::Paren));
            if let Some(role) = &declared_role
                && *role != STRUCTURAL_ATTRIBUTE
            {
                return Err(syn::Error::new_spanned(
                    role,
                    format_args!("invalid ryft member universe role '{role}'; only 'structural' is supported here"),
                ));
            }
            let structural = declared_role.is_some();
            let member_type = if structural {
                content.parse::<syn::Ident>()?;
                let role_content;
                syn::parenthesized!(role_content in content);
                let member_type = role_content.parse::<syn::Type>()?;
                if !role_content.is_empty() {
                    return Err(role_content.error("'structural(...)' declares exactly one member type"));
                }
                member_type
            } else {
                content.parse::<syn::Type>()?
            };
            if members.iter().any(|member| type_tokens_equal(&member.r#type, &member_type)) {
                return Err(syn::Error::new_spanned(
                    &member_type,
                    format_args!(
                        "duplicate ryft member universe '{}'",
                        member_type.to_token_stream().to_string().replace(' ', ""),
                    ),
                ));
            }
            members.push(OperationMember { r#type: member_type, structural });
            if content.is_empty() {
                break;
            }
            content.parse::<syn::Token![,]>()?;
        }
        self.members = members;
        Ok(())
    }

    /// Extracts the [`OperationVariant`]s that are contained in the provided [`syn::DeriveInput`]. This function
    /// also checks that the input is an enum, because the operation derives do not support structs or unions.
    fn extract_variants(&mut self, input: &syn::DeriveInput) -> Vec<OperationVariant> {
        let syn::Data::Enum(data) = &input.data else {
            self.add_error(&input.ident, "the '#[derive(Operation)]' macro only supports enums");
            return Vec::new();
        };

        let members = self.members.clone();
        data.variants
            .iter()
            .filter_map(|variant| self.extract_variant(&input.generics, members.as_slice(), variant))
            .collect()
    }

    /// Normalizes the enum metadata shared by all generated implementations.
    fn normalize_input(&mut self, input: &syn::DeriveInput) -> Option<OperationEnum> {
        let variants = self.extract_variants(input);
        let mut member_types = std::collections::HashSet::new();
        for variant in &variants {
            if let Some(member_type) = variant.class.projected_member_type()
                && !member_types.insert(member_type.to_token_stream().to_string())
            {
                self.add_error(
                    &variant.ident,
                    format_args!(
                        "operation family declares member type '{}' more than once",
                        member_type.to_token_stream().to_string().replace(' ', ""),
                    ),
                );
            }
        }
        if self.has_errors() {
            return None;
        }

        let operation_type = self.operation_type.clone()?;

        let ident = input.ident.clone();
        let generics = input.generics.clone();
        let conversion_generics = generics.without_defaults();
        let (_, type_generics, _) = conversion_generics.split_for_impl();
        let self_type: syn::Type = syn::parse_quote!(#ident #type_generics);
        let value_type_parameters = value_type_parameters(&generics, &operation_type);
        let (program_constant_type, program_constant_parameter, has_separate_runtime_value_type) =
            if let Some(program_constant_type) = self.program_constant_type.clone() {
                (program_constant_type, None, true)
            } else {
                let Some(program_constant_parameter) = value_type_parameters.first().cloned() else {
                    self.add_error(
                        &generics,
                        "could not infer the program constant value type for '#[derive(Operation)]'",
                    );
                    return None;
                };
                let program_constant_type: syn::Type = syn::parse_quote!(#program_constant_parameter);
                let has_separate_runtime_value_type = value_type_parameters.len() == 1;
                (program_constant_type, Some(program_constant_parameter), has_separate_runtime_value_type)
            };
        let program_value_substitutions = program_constant_parameter
            .as_ref()
            .map(|parameter| program_value_substitutions(&value_type_parameters, parameter))
            .unwrap_or_default();
        let program_self_type = substitute_type_idents(&self_type, &program_value_substitutions);
        let operation_generics = operation_generics(&generics, &variants, &self.ryft_crate, &operation_type);
        let program_generics = substitute_generics(&operation_generics, &program_value_substitutions);
        let variants = variants
            .into_iter()
            .map(|mut variant| {
                variant.program_payload_type =
                    substitute_type_idents(&variant.payload_type, &program_value_substitutions);
                variant.class.substitute_type_idents(&program_value_substitutions);
                variant
            })
            .collect();

        let members = self
            .members
            .iter()
            .map(|member| OperationMember {
                r#type: substitute_type_idents(&member.r#type, &program_value_substitutions),
                structural: member.structural,
            })
            .collect();

        Some(OperationEnum {
            ryft_crate: self.ryft_crate.clone(),
            operation_type,
            members,
            dispatchers: self.dispatchers.unwrap_or_default(),
            ident,
            generics,
            conversion_generics,
            operation_generics,
            self_type,
            has_separate_runtime_value_type,
            program_constant_type,
            program_constant_parameter,
            program_generics,
            program_self_type,
            variants,
        })
    }

    /// Extracts one [`OperationVariant`] from the provided [`syn::Variant`]. This function also checks that the
    /// variant is a tuple variant with exactly one payload field and rejects nested `#[ryft(...)]` attributes on
    /// that field.
    ///
    /// # Parameters
    ///
    ///   - `generics`: [`syn::Generics`] of the enum being derived, used to detect bare generic payloads.
    ///   - `members`: Member universes declared by the enum, used to default and cross-check member markers.
    ///   - `variant`: [`syn::Variant`] from which to extract an [`OperationVariant`].
    fn extract_variant(
        &mut self,
        generics: &syn::Generics,
        members: &[OperationMember],
        variant: &syn::Variant,
    ) -> Option<OperationVariant> {
        let (class, generate_from) = self.extract_variant_attributes(members, variant);
        let syn::Fields::Unnamed(fields) = &variant.fields else {
            self.add_error(&variant.ident, "operation enum variants must be tuple variants with one payload field");
            return None;
        };
        if fields.unnamed.len() != 1 {
            self.add_error(&variant.fields, "operation enum variants must have exactly one payload field");
            return None;
        }
        let field = fields.unnamed.first().expect("expected one payload field");
        field.attrs.iter().filter(|attribute| attribute.path() == &RYFT_ATTRIBUTE).for_each(|attribute| {
            self.add_error(
                attribute,
                "operation field attributes are not supported; put operation member-class attributes on the \
                     enclosing variant",
            )
        });

        let payload_type = field.ty.clone();
        let (operation_type, is_boxed) = boxed_inner_type(&payload_type)
            .map(|operation_type| (operation_type, true))
            .unwrap_or_else(|| (payload_type.clone(), false));
        let is_generic_extension = is_bare_generic_parameter(&payload_type, generics);

        Some(OperationVariant {
            class,
            ident: variant.ident.clone(),
            program_payload_type: operation_type.clone(),
            payload_type: operation_type,
            is_boxed,
            is_generic_extension,
            generate_from,
        })
    }

    /// Extracts the semantic class and conversion policy declared for `variant`. Variants without a class marker are
    /// composite-native and retain their payload's direct outer-family contract. A `projected` member has its complete
    /// instruction boundary projected into its member [`Type`](ryft_core::Type), while a `mixed` member keeps a native
    /// member payload whose parent instruction has a genuinely mixed boundary. Both classes accept the optional
    /// `structural` role, and a `mixed` marker may omit its member type entirely when the enum declares exactly one
    /// computational member universe. `skip_from` suppresses only the generated `From<Payload>` implementation so a
    /// semantic normalizing conversion can remain handwritten; borrowed `TryFrom` projection is still generated.
    ///
    /// # Parameters
    ///
    ///   - `members`: Member universes declared by the enum, used to default and cross-check member markers.
    ///   - `variant`: [`syn::Variant`] whose class marker and conversion policy are extracted.
    fn extract_variant_attributes(
        &mut self,
        members: &[OperationMember],
        variant: &syn::Variant,
    ) -> (OperationVariantClass, bool) {
        let mut class: Option<OperationVariantClass> = None;
        let mut generate_from = true;
        for attribute in variant.attrs.iter().filter(|attribute| attribute.path() == &RYFT_ATTRIBUTE) {
            attribute
                .parse_nested_meta(|meta| {
                    if meta.path == SKIP_FROM_ATTRIBUTE {
                        if !generate_from {
                            return Err(meta.error("duplicate ryft operation variant attribute 'skip_from'"));
                        }
                        generate_from = false;
                        return Ok(());
                    }
                    let candidate = match &meta.path {
                        path if path == &PROJECTED_ATTRIBUTE => {
                            let (member_type, structural) = parse_member_class(&meta, members, false)?;
                            OperationVariantClass::ProjectedMember { member_type, structural }
                        }
                        path if path == &MIXED_ATTRIBUTE => {
                            let (member_type, structural) = parse_member_class(&meta, members, true)?;
                            OperationVariantClass::MixedMember { member_type, structural }
                        }
                        path if path == &STRUCTURAL_ATTRIBUTE => {
                            return Err(meta.error(
                                "the 'structural' operation variant class was replaced by the \
                                 'projected(U, structural)' role form",
                            ));
                        }
                        _ => {
                            return Err(meta.error(format_args!(
                                "invalid operation variant '#[ryft(...)]' attribute: '{}'; only 'projected', \
                                 'mixed', and 'skip_from' are supported here",
                                meta.path.to_token_stream().to_string().replace(' ', ""),
                            )));
                        }
                    };
                    if let Some(class) = &class {
                        let message = if class.name() == candidate.name() {
                            format!("duplicate ryft operation variant class '{}'", candidate.name())
                        } else {
                            format!(
                                "contradictory ryft operation variant classes '{}' and '{}'",
                                class.name(),
                                candidate.name(),
                            )
                        };
                        return Err(syn::Error::new_spanned(&meta.path, message));
                    }
                    class = Some(candidate);
                    Ok(())
                })
                .unwrap_or_else(|error| self.errors.push(error));
        }
        (class.unwrap_or(OperationVariantClass::CompositeNative), generate_from)
    }
}

/// Parses the shared `class(U)` or `class(U, structural)` member class grammar used by both the `projected` and the
/// `mixed` boundary markers: the member [`Type`](ryft_core::Type) `U` the payload declares, optionally followed by the
/// `structural` transform role. Returns the member type together with whether the structural role was declared, so
/// that omitting the role selects the computational default.
///
/// A boundary that permits a defaulted member type additionally accepts the two abbreviated forms `class` and
/// `class(structural)`, which take their data universe from the enum's single declared computational member. The
/// abbreviated role form makes the first argument position role-valued rather than type-valued, so a lone
/// `structural` identifier that is not followed by a comma is parsed as the role instead of as a member type.
///
/// # Parameters
///
///   - `meta`: Nested `#[ryft(...)]` meta item naming the boundary marker.
///   - `members`: Member universes declared by the enum, used to default and cross-check the member type.
///   - `allow_defaulted_member_type`: Whether this boundary accepts the abbreviated forms that omit the member type.
fn parse_member_class(
    meta: &syn::meta::ParseNestedMeta,
    members: &[OperationMember],
    allow_defaulted_member_type: bool,
) -> syn::Result<(syn::Type, bool)> {
    let class = meta.path.to_token_stream().to_string();
    if allow_defaulted_member_type && !meta.input.peek(syn::token::Paren) {
        return Ok((defaulted_member_type(&meta.path, &class, members)?, false));
    }

    let content;
    syn::parenthesized!(content in meta.input);
    let role = content.fork();
    if allow_defaulted_member_type
        && role.parse::<syn::Ident>().is_ok_and(|role| role == STRUCTURAL_ATTRIBUTE)
        && role.is_empty()
    {
        let role = content.parse::<syn::Ident>()?;
        return Ok((defaulted_member_type(&role, &class, members)?, true));
    }
    let member_type = content.parse::<syn::Type>()?;
    let mut structural = false;
    if content.parse::<Option<syn::Token![,]>>()?.is_some() {
        let role = content.parse::<syn::Ident>()?;
        if role != STRUCTURAL_ATTRIBUTE {
            return Err(syn::Error::new_spanned(
                &role,
                format_args!("invalid {class} operation variant role '{role}'; only 'structural' is supported here"),
            ));
        }
        structural = true;
    }
    if !content.is_empty() {
        return Err(content.error(format_args!(
            "the '{class}' operation variant class accepts one member type and an optional role",
        )));
    }
    if !members.is_empty() && !members.iter().any(|member| type_tokens_equal(&member.r#type, &member_type)) {
        return Err(syn::Error::new_spanned(
            &member_type,
            format_args!(
                "the '{class}' operation variant class declares member type '{}', which the operation family does not \
                 declare in '#[ryft(members(...))]'",
                member_type.to_token_stream().to_string().replace(' ', ""),
            ),
        ));
    }
    Ok((member_type, structural))
}

/// Returns the data universe an abbreviated member class marker defaults to: the enum's single declared computational
/// member universe. Families that declare no members, or that declare several computational members, cannot default
/// it and must name the member type explicitly.
///
/// # Parameters
///
///   - `tokens`: Tokens the diagnostic spans when the member type cannot be defaulted.
///   - `class`: Name of the boundary marker being parsed, used in diagnostics.
///   - `members`: Member universes declared by the enum.
fn defaulted_member_type<T: ToTokens>(tokens: T, class: &str, members: &[OperationMember]) -> syn::Result<syn::Type> {
    let computational_members =
        members.iter().filter(|member| !member.structural).map(|member| &member.r#type).collect::<Vec<_>>();
    match computational_members.as_slice() {
        [member_type] => Ok((*member_type).clone()),
        [] if members.is_empty() => Err(syn::Error::new_spanned(
            tokens.into_token_stream(),
            format_args!(
                "the '{class}' operation variant class cannot default its member type because the operation family \
                 declares no '#[ryft(members(...))]'; declare the family's members or name the member type as \
                 '{class}(U)'",
            ),
        )),
        _ => Err(syn::Error::new_spanned(
            tokens.into_token_stream(),
            format_args!(
                "the '{class}' operation variant class cannot default its member type because the operation family \
                 declares {} computational member universes; name the member type as '{class}(U)'",
                computational_members.len(),
            ),
        )),
    }
}

impl OperationEnum {
    /// Generates every semantic implementation selected for this operation enum.
    fn generate(&self) -> TokenStream {
        let operation = self.generate_operation();
        let batching = self.dispatchers.batching.then(|| self.generate_batchable_operation());
        let differentiation = self.dispatchers.differentiation.then(|| self.generate_differentiable_operation());
        let transposition = self.dispatchers.transposition.then(|| self.generate_transposable_operation());
        quote!(#operation #batching #differentiation #transposition)
    }

    /// Generates the `Operation` derive output: the [`Operation`] dispatcher, the [`InterpretableOperation`]
    /// dispatcher, the
    /// [`PartiallyEvaluatableOperation`] dispatcher, the [`Display`] implementation, and the `From` and borrowed
    /// `TryFrom` payload conversions. Refer to the documentation of the [`Operation`] trait for information on the
    /// shape of the generated code and on how the interpretation value types are inferred from the enum's
    /// `Value<Type = T>` generic parameters.
    fn generate_operation(&self) -> TokenStream {
        let variants = &self.variants;
        let ryft = &self.ryft_crate;
        let operation_self_type = &self.self_type;
        let operation_generics = &self.operation_generics;
        let (operation_impl_generics, _, operation_where_clause) = operation_generics.split_for_impl();
        let operation = self.generate_operation_dispatcher();
        let interpretation = self.generate_interpretable_operation();
        let partial_evaluation = self.generate_partially_evaluatable_operation();
        let projections = variants.iter().filter_map(|variant| self.generate_operation_projection_impl(variant));
        let conversion_impls = variants
            .iter()
            .filter(|variant| !variant.is_generic_extension)
            .map(|variant| self.generate_conversion_impl(variant));

        const_block(quote! {
            #operation

            #interpretation

            #partial_evaluation

            #(#projections)*

            #[automatically_derived]
            impl #operation_impl_generics ::std::fmt::Display for #operation_self_type
            #operation_where_clause
            {
                fn fmt(&self, formatter: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result {
                    <Self as #ryft::Operation>::render(self, formatter, 0)
                }
            }

            #(#conversion_impls)*
        })
    }

    /// Generates the base [`Operation`] dispatcher.
    fn generate_operation_dispatcher(&self) -> TokenStream {
        let ryft = &self.ryft_crate;
        let primary_type = &self.operation_type;
        let operation_self_type = &self.self_type;
        let (impl_generics, _, where_clause) = self.operation_generics.split_for_impl();
        let name_arms = self.variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            let payload_type = &variant.payload_type;
            let receiver = variant.receiver();
            quote! {
                Self::#variant_ident(operation) => {
                    <#payload_type as #ryft::Operation>::name(#receiver)
                },
            }
        });
        let infer_output_type_arms = self.variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            let payload_type = &variant.payload_type;
            let receiver = variant.receiver();
            match &variant.class {
                OperationVariantClass::MixedMember { .. } => quote! {
                    Self::#variant_ident(operation) => {
                        <#payload_type as #ryft::MemberOperation<#primary_type>>::infer_parent_output_types(
                            #receiver,
                            input_types,
                            region_interfaces,
                        )
                    },
                },
                OperationVariantClass::CompositeNative => quote! {
                    Self::#variant_ident(operation) => {
                        <#payload_type as #ryft::Operation>::infer_output_types(
                            #receiver,
                            input_types,
                            region_interfaces,
                        )
                    },
                },
                OperationVariantClass::ProjectedMember { .. } => {
                    quote! {
                        Self::#variant_ident(operation) => {
                            #ryft::infer_projected_operation_output_types(
                                #receiver,
                                input_types,
                                region_interfaces,
                            )
                        },
                    }
                }
            }
        });
        let type_identity_renaming_arms = self.variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            let payload_type = &variant.payload_type;
            let receiver = variant.receiver();
            let rename = if matches!(variant.class, OperationVariantClass::MixedMember { .. }) {
                quote! {
                    <#payload_type as #ryft::MemberOperation<#primary_type>>::rename_parent_type_identities(
                        #receiver,
                        renaming,
                    )?
                }
            } else {
                quote! {
                    <#payload_type as #ryft::Operation>::rename_type_identities(
                        #receiver,
                        renaming,
                    )?
                }
            };
            let renamed = if variant.is_boxed {
                quote! {
                    ::std::boxed::Box::new(#rename)
                }
            } else {
                rename
            };
            quote! {
                Self::#variant_ident(operation) => {
                    ::std::result::Result::Ok(Self::#variant_ident(#renamed))
                },
            }
        });
        let region_instantiation_arms = self.variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            let payload_type = &variant.payload_type;
            let receiver = variant.receiver();
            match &variant.class {
                OperationVariantClass::MixedMember { .. } => quote! {
                    Self::#variant_ident(operation) => {
                        <#payload_type as #ryft::MemberOperation<#primary_type>>::infer_parent_region_input_types(
                            #receiver,
                            input_types,
                            region_interfaces,
                        )
                    },
                },
                OperationVariantClass::ProjectedMember { .. } => {
                    quote! {
                        Self::#variant_ident(operation) => {
                            #ryft::infer_projected_operation_region_input_types(
                                #receiver,
                                input_types,
                                region_interfaces,
                            )
                        },
                    }
                }
                OperationVariantClass::CompositeNative => quote! {
                    Self::#variant_ident(operation) => {
                        <#payload_type as #ryft::Operation>::infer_region_input_types(
                            #receiver,
                            input_types,
                            region_interfaces,
                        )
                    },
                },
            }
        });
        let region_slot_arms = self.variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            let payload_type = &variant.payload_type;
            let receiver = variant.receiver();
            quote! {
                Self::#variant_ident(operation) => {
                    <#payload_type as #ryft::Operation>::region_slots(#receiver)
                },
            }
        });
        let provenance_arms = self.variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            let payload_type = &variant.payload_type;
            let receiver = variant.receiver();
            quote! {
                Self::#variant_ident(operation) => {
                    <#payload_type as #ryft::Operation>::output_region_provenance(
                        #receiver,
                        output_index,
                    )
                },
            }
        });
        let is_zero_arms = self.variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            let payload_type = &variant.payload_type;
            let receiver = variant.receiver();
            quote! {
                Self::#variant_ident(operation) => {
                    <#payload_type as #ryft::Operation>::is_zero(#receiver, output_index)
                },
            }
        });
        let effects_arms = self.variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            let payload_type = &variant.payload_type;
            let receiver = variant.receiver();
            quote! {
                Self::#variant_ident(operation) => {
                    <#payload_type as #ryft::Operation>::effects(#receiver)
                },
            }
        });
        let render_arms = self.variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            let payload_type = &variant.payload_type;
            let receiver = variant.receiver();
            quote! {
                Self::#variant_ident(operation) => {
                    <#payload_type as #ryft::Operation>::render(#receiver, formatter, indentation)
                },
            }
        });

        quote! {
            #[automatically_derived]
            impl #impl_generics #ryft::Operation for #operation_self_type
            #where_clause
            {
                type Type = #primary_type;

                fn name(&self) -> &'static str {
                    match self { #(#name_arms)* }
                }

                fn region_slots(&self) -> &'static [#ryft::RegionSlot] {
                    match self { #(#region_slot_arms)* }
                }

                fn infer_region_input_types(
                    &self,
                    input_types: &[#primary_type],
                    region_interfaces: &[#ryft::RegionInterface<#primary_type>],
                ) -> ::std::result::Result<
                    ::std::vec::Vec<::std::option::Option<::std::vec::Vec<#primary_type>>>,
                    #ryft::TypeError,
                > {
                    match self { #(#region_instantiation_arms)* }
                }

                fn infer_output_types(
                    &self,
                    input_types: &[#primary_type],
                    region_interfaces: &[#ryft::RegionInterface<#primary_type>],
                ) -> ::std::result::Result<::std::vec::Vec<#primary_type>, #ryft::TypeError> {
                    match self { #(#infer_output_type_arms)* }
                }

                fn output_region_provenance(
                    &self,
                    output_index: usize,
                ) -> ::std::vec::Vec<#ryft::OutputRegionProvenance> {
                    match self { #(#provenance_arms)* }
                }

                fn is_zero(&self, output_index: usize) -> bool {
                    match self { #(#is_zero_arms)* }
                }

                fn effects(&self) -> #ryft::Effects {
                    match self { #(#effects_arms)* }
                }

                fn rename_type_identities(
                    &self,
                    renaming: &#ryft::TypeIdentityRenaming<
                        <#primary_type as #ryft::Type>::Identity,
                    >,
                ) -> ::std::result::Result<Self, #ryft::TypeError> {
                    match self { #(#type_identity_renaming_arms)* }
                }

                fn render(
                    &self,
                    formatter: &mut ::std::fmt::Formatter<'_>,
                    indentation: usize,
                ) -> ::std::fmt::Result {
                    match self { #(#render_arms)* }
                }
            }
        }
    }

    /// Generates the always-present [`InterpretableOperation`] dispatcher.
    fn generate_interpretable_operation(&self) -> TokenStream {
        let ryft = &self.ryft_crate;
        let interpretation_self_type = &self.program_self_type;
        let interpretation_generics = self.interpretation_generics();
        let (interpretation_impl_generics, _, interpretation_where_clause) = interpretation_generics.split_for_impl();
        let interpretation_arms = self.variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            let payload_operation_type = &variant.program_payload_type;
            let receiver = variant.receiver();
            match &variant.class {
                OperationVariantClass::ProjectedMember { .. } => {
                    quote! {
                        Self::#variant_ident(operation) => {
                            #ryft::interpret_projected_operation(context, #receiver, driver, inputs)
                        },
                    }
                }
                OperationVariantClass::MixedMember { .. } => quote! {
                    Self::#variant_ident(operation) => {
                        <#payload_operation_type as #ryft::MemberInterpretableOperation<__Context>>::
                            interpret_in_parent(#receiver, context, driver, inputs)
                    },
                },
                OperationVariantClass::CompositeNative => quote! {
                    Self::#variant_ident(operation) => {
                        <#payload_operation_type as #ryft::InterpretableOperation<__Context>>::interpret(
                            #receiver,
                            context,
                            driver,
                            inputs,
                        )
                    },
                },
            }
        });

        quote! {
            #[automatically_derived]
            impl #interpretation_impl_generics
                #ryft::InterpretableOperation<__Context>
                for #interpretation_self_type
            #interpretation_where_clause
            {
                fn interpret<__D: #ryft::InterpretationDriver<__Context>>(
                    &self,
                    context: &__Context,
                    driver: &__D,
                    inputs: &[<__Context as #ryft::Domain>::Value],
                ) -> ::std::result::Result<
                    ::std::vec::Vec<<__Context as #ryft::Domain>::Value>,
                    #ryft::ProgramError,
                > {
                    match self {
                        #(#interpretation_arms)*
                    }
                }
            }
        }
    }

    /// Generates the always-present [`PartiallyEvaluatableOperation`] dispatcher.
    fn generate_partially_evaluatable_operation(&self) -> TokenStream {
        let ryft = &self.ryft_crate;
        let primary_type = &self.operation_type;
        let partial_evaluation_self_type = &self.program_self_type;
        let partial_evaluation_value_type = &self.program_constant_type;
        let mut generics = self.program_generics.clone();
        generics.params.push(syn::parse_quote!(__Context));
        let where_clause = generics.make_where_clause();
        where_clause.predicates.push(syn::parse_quote! {
            __Context: #ryft::Context<
                Type = #primary_type,
                Constant = #partial_evaluation_value_type,
                Operation = #partial_evaluation_self_type,
            >
        });

        // Bare generic extension payloads and member payloads use the complete enum operation's canonical
        // fold-or-residualize path instead of naming a payload rule in the composite context. A member payload's own
        // partial-evaluation rule belongs to its native context and cannot consume composite partial values without a
        // separate parent-boundary contract.
        where_clause.predicates.extend(
            self.variants
                .iter()
                .filter(|variant| {
                    !variant.is_generic_extension && matches!(variant.class, OperationVariantClass::CompositeNative)
                })
                .map(|variant| {
                    let operation_type = &variant.program_payload_type;
                    let predicate: syn::WherePredicate = syn::parse_quote! {
                        #operation_type: #ryft::PartiallyEvaluatableOperation<__Context>
                    };
                    predicate
                }),
        );
        let arms = self.variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            if variant.is_generic_extension || !matches!(variant.class, OperationVariantClass::CompositeNative) {
                quote! {
                    Self::#variant_ident(_) => {
                        let regions = driver
                            .regions()
                            .into_iter()
                            .map(|region| region.to_program())
                            .collect();
                        context.fold_or_residualize(self.clone(), regions, inputs)
                    },
                }
            } else {
                let operation_type = &variant.program_payload_type;
                let receiver = variant.receiver();
                quote! {
                    Self::#variant_ident(operation) => {
                        <#operation_type as #ryft::PartiallyEvaluatableOperation<__Context>>::
                            partially_evaluate(#receiver, context, driver, inputs)
                    },
                }
            }
        });
        let (impl_generics, _, where_clause) = generics.split_for_impl();

        quote! {
            #[automatically_derived]
            impl #impl_generics
                #ryft::PartiallyEvaluatableOperation<__Context>
                for #partial_evaluation_self_type
            #where_clause
            {
                fn partially_evaluate<__D: #ryft::PartialEvaluationDriver<__Context>>(
                    &self,
                    context: &#ryft::PartialEvaluationContext<__Context>,
                    driver: &__D,
                    inputs: &[#ryft::PartialEvaluationValue<
                        <__Context as #ryft::Domain>::Value,
                    >],
                ) -> ::std::result::Result<
                    ::std::vec::Vec<#ryft::PartialEvaluationValue<
                        <__Context as #ryft::Domain>::Value,
                    >>,
                    #ryft::ProgramError,
                > {
                    match self {
                        #(#arms)*
                    }
                }
            }
        }
    }

    /// Generates the [`BatchableOperation`](ryft_core::BatchableOperation) dispatcher. Inferred homogeneous array
    /// families remain generic over their array batching mode. Explicitly declared families use the canonical policy
    /// selected by [`BatchableType`](ryft_core::BatchableType). Composite-native variants delegate directly, projected
    /// members use `batch_projected_operation` in either role, and mixed members use their parent-universe rule.
    fn generate_batchable_operation(&self) -> TokenStream {
        let variants = &self.variants;
        let ryft = &self.ryft_crate;
        let primary_type = &self.operation_type;
        let program_constant_type = &self.program_constant_type;
        let batching_self_type = &self.program_self_type;
        let has_explicit_operation_family = self.program_constant_parameter.is_none();
        let batching_policy: syn::Type = if has_explicit_operation_family {
            syn::parse_quote!(__BatchingPolicy)
        } else {
            syn::parse_quote!(#ryft::ArrayBatching<__P>)
        };
        let parent_value_type: syn::Type = syn::parse_quote!(<__ParentContext as #ryft::Domain>::Value);
        let batch_type: syn::Type = if has_explicit_operation_family {
            syn::parse_quote!(<#batching_policy as #ryft::BatchingPolicy<__ParentContext>>::Batch)
        } else {
            syn::parse_quote!(#ryft::ArrayBatch<#parent_value_type>)
        };
        let mut batching_generics = self.program_generics.clone();
        batching_generics.params.push(syn::parse_quote!(__ParentContext));
        if has_explicit_operation_family {
            batching_generics.params.push(syn::parse_quote!(__BatchingPolicy));
        } else {
            batching_generics.params.push(syn::parse_quote!(__P));
        }
        let batching_where_clause = batching_generics.make_where_clause();
        batching_where_clause.predicates.push(syn::parse_quote! {
            __ParentContext: #ryft::Context<
                Type = #primary_type,
                Constant = #program_constant_type,
                Operation = #batching_self_type,
            >
        });
        batching_where_clause.predicates.push(syn::parse_quote! {
            #batching_self_type: #ryft::Operation<Type = #primary_type>
        });
        if has_explicit_operation_family {
            batching_where_clause.predicates.push(syn::parse_quote! {
                #primary_type: #ryft::BatchableType<Policy = __BatchingPolicy>
            });
            batching_where_clause.predicates.push(syn::parse_quote! {
                #batching_policy: #ryft::BatchingPolicy<__ParentContext>
            });
        } else {
            batching_where_clause
                .predicates
                .push(syn::parse_quote!(__P: #ryft::ArrayBatchingPolicy<__ParentContext>));
        }
        for variant in variants {
            let operation_type = &variant.program_payload_type;
            match &variant.class {
                OperationVariantClass::CompositeNative => batching_where_clause.predicates.push(syn::parse_quote! {
                    #operation_type: #ryft::BatchableOperation<
                        __ParentContext,
                        #batching_policy,
                    >
                }),
                OperationVariantClass::MixedMember { .. } => batching_where_clause.predicates.push(syn::parse_quote! {
                    #operation_type: #ryft::MemberBatchableOperation<__ParentContext, #batching_policy>
                }),
                OperationVariantClass::ProjectedMember { member_type, .. } => {
                    batching_where_clause.predicates.push(syn::parse_quote! {
                        #program_constant_type: #ryft::ValueProjection<
                            #member_type,
                            Projected: #ryft::Value<Type = #member_type>,
                        >
                    });
                    batching_where_clause.predicates.push(syn::parse_quote! {
                        <__ParentContext as #ryft::Domain>::Constant: #ryft::ValueProjection<
                            #member_type,
                            Projected: #ryft::Value<Type = #member_type>,
                        >
                    });
                    batching_where_clause.predicates.push(syn::parse_quote! {
                        <__ParentContext as #ryft::Domain>::Value: #ryft::ValueProjection<
                            #member_type,
                            Projected: #ryft::Value<Type = #member_type>,
                        >
                    });
                    batching_where_clause.predicates.push(syn::parse_quote! {
                        <__ParentContext as #ryft::Domain>::Operation: #ryft::OperationProjection<
                            #member_type,
                            Projected = #operation_type,
                        >
                    });
                    batching_where_clause.predicates.push(syn::parse_quote! {
                        #batching_policy: #ryft::BatchingPolicyProjection<__ParentContext, #member_type>
                    });
                    batching_where_clause.predicates.push(syn::parse_quote! {
                        #operation_type: #ryft::BatchableOperation<
                            #ryft::ProjectedContext<__ParentContext, #member_type>,
                            <#batching_policy as #ryft::BatchingPolicyProjection<
                                __ParentContext,
                                #member_type,
                            >>::Projected,
                        >
                    });
                }
            }
        }

        // Recursive higher-order rules seed accumulators through the parent context's `Zero` capability. All other
        // value requirements are transported by the per-payload batching predicates above.
        batching_where_clause
            .predicates
            .push(syn::parse_quote!(__ParentContext: #ryft::Zero<#parent_value_type>));
        let batching_arms = variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            let operation_type = &variant.program_payload_type;
            let receiver = variant.receiver();
            match &variant.class {
                OperationVariantClass::CompositeNative => quote! {
                    Self::#variant_ident(operation) => {
                        <#operation_type as #ryft::BatchableOperation<
                            __ParentContext,
                            #batching_policy,
                        >>::batch(#receiver, context, driver, inputs)
                    },
                },
                OperationVariantClass::MixedMember { .. } => quote! {
                    Self::#variant_ident(operation) => {
                        <#operation_type as #ryft::MemberBatchableOperation<
                            __ParentContext,
                            #batching_policy,
                        >>::batch_in_parent(#receiver, context, driver, inputs)
                    },
                },
                OperationVariantClass::ProjectedMember { .. } => {
                    quote! {
                        Self::#variant_ident(operation) => {
                            #ryft::batch_projected_operation(context, #receiver, inputs)
                        },
                    }
                }
            }
        });
        let (batching_impl_generics, _, batching_where_clause) = batching_generics.split_for_impl();
        const_block(quote! {
            #[automatically_derived]
            impl #batching_impl_generics #ryft::BatchableOperation<
                __ParentContext,
                #batching_policy,
            > for #batching_self_type
            #batching_where_clause
            {
                fn batch<__D: #ryft::BatchingDriver<
                    __ParentContext,
                    #batching_policy,
                >>(
                    &self,
                    context: &#ryft::BatchingContext<
                        __ParentContext,
                        #batching_policy,
                    >,
                    driver: &__D,
                    inputs: &[#batch_type],
                ) -> ::std::result::Result<
                    #ryft::BatchedOutputs<__ParentContext, #batching_policy>,
                    #ryft::BatchingError,
                > {
                    match self {
                        #(#batching_arms)*
                    }
                }
            }
        })
    }

    /// Returns the computational member universes an output of a structural mixed payload can belong to: the payload's
    /// own data universe first, followed by every other computational member universe this family declares through
    /// `#[ryft(members(...))]`. A family that declares no members exposes only the payload's own data universe, so a
    /// single-universe family generates exactly the classification it had before member universes were declarable.
    fn tangent_universes(&self, member_type: &syn::Type) -> Vec<syn::Type> {
        std::iter::once(member_type.clone())
            .chain(
                self.members
                    .iter()
                    .filter(|member| !member.structural)
                    .map(|member| member.r#type.clone())
                    .filter(|declared_type| !type_tokens_equal(declared_type, member_type)),
            )
            .collect()
    }

    /// Generates the forward-mode (JVP) dispatcher of the `DifferentiableOperation` derive output.
    ///
    /// The generated implementation is generic over a `__DifferentiationContext` staging context pinned to the enum's
    /// primary type, program constant type, and the enum itself as its operation family. Every variant forwards to its
    /// payload's own `DifferentiableOperation` rule. Every payload carries a direct per-variant predicate that
    /// transports the rule's own capability requirements. Higher-order rules request nested differentiation through
    /// their instruction-scoped driver, whose concrete implementation establishes the finite `Program::jvp` and
    /// `Program::linearize` bounds at its construction site.
    fn generate_differentiable_operation(&self) -> TokenStream {
        let variants = &self.variants;
        let ryft = &self.ryft_crate;
        let primary_type = &self.operation_type;
        let program_constant_type = &self.program_constant_type;
        let differentiation_self_type = &self.program_self_type;
        let mut differentiation_generics = self.program_generics.clone();
        differentiation_generics.params.push(syn::parse_quote!(__DifferentiationContext));
        let where_clause = differentiation_generics.make_where_clause();
        where_clause.predicates.push(syn::parse_quote! {
            __DifferentiationContext: #ryft::Context<
                Type = #primary_type,
                Constant = #program_constant_type,
                Operation = #differentiation_self_type,
            >
        });
        where_clause.predicates.push(syn::parse_quote! {
            #differentiation_self_type: #ryft::Operation<Type = #primary_type>
        });
        // Higher-order payload rules materialize structural zero tangents at sub-program boundaries through the
        // context's `Zero` capability, so the dispatcher transports that requirement explicitly. Staging contexts
        // satisfy it through the blanket staging `Zero` implementation and eager domains implement it directly.
        where_clause.predicates.push(syn::parse_quote! {
            __DifferentiationContext: #ryft::Zero<<__DifferentiationContext as #ryft::Domain>::Value>
        });
        // The `while` rule concretizes data-dependent loop predicates on the carried values when the context is
        // eager, so the dispatcher also transports the `Concretizable<bool>` value requirement. Staged values satisfy
        // it through the tracer `Concretizable<bool>` implementation (whose `concretize` defers with an error) and
        // eager values implement it directly.
        where_clause.predicates.push(syn::parse_quote! {
            <__DifferentiationContext as #ryft::Domain>::Value: #ryft::Concretizable<bool>
        });
        for variant in variants {
            let operation_type = &variant.program_payload_type;
            match &variant.class {
                OperationVariantClass::CompositeNative => where_clause.predicates.push(syn::parse_quote! {
                    #operation_type: #ryft::DifferentiableOperation<__DifferentiationContext>
                }),
                OperationVariantClass::ProjectedMember { structural: false, .. }
                | OperationVariantClass::MixedMember { structural: false, .. } => {
                    where_clause.predicates.push(syn::parse_quote! {
                        #operation_type: #ryft::MemberDifferentiableOperation<__DifferentiationContext>
                    });
                }
                // A structural mixed payload stages its own primal and a matching zero tangent over the same
                // parent-universe operands, so the dispatcher needs the member zero constructor and the member view of
                // the payload's declared parent output types.
                OperationVariantClass::MixedMember { member_type, structural: true } => {
                    where_clause.predicates.push(syn::parse_quote! {
                        #member_type: #ryft::DifferentiableType
                    });
                    where_clause.predicates.push(syn::parse_quote! {
                        #operation_type: #ryft::MemberOperation<#primary_type>
                    });
                    where_clause.predicates.push(syn::parse_quote! {
                        #differentiation_self_type: ::std::convert::From<#ryft::ZeroOperation<#member_type>>
                    });
                    where_clause.predicates.push(syn::parse_quote! {
                        for<'__t> &'__t #member_type:
                            ::std::convert::TryFrom<&'__t #primary_type, Error = #ryft::TypeError>
                    });
                    // An output may also belong to another computational member universe the family declares, and each
                    // such universe needs its own zero constructor and member type view.
                    for tangent_universe in self.tangent_universes(member_type).into_iter().skip(1) {
                        where_clause.predicates.push(syn::parse_quote! {
                            #tangent_universe: #ryft::DifferentiableType
                        });
                        where_clause.predicates.push(syn::parse_quote! {
                            #differentiation_self_type: ::std::convert::From<#ryft::ZeroOperation<#tangent_universe>>
                        });
                        where_clause.predicates.push(syn::parse_quote! {
                            for<'__t> &'__t #tangent_universe:
                                ::std::convert::TryFrom<&'__t #primary_type, Error = #ryft::TypeError>
                        });
                    }
                }
                OperationVariantClass::ProjectedMember { structural: true, .. } => {}
            }
        }
        // Higher-order payload rules (condition/while/scan) forward-differentiate and linearize their nested
        // programs through the call-scoped `DifferentiationDriver`, whose implementations carry the direct
        // `Program::jvp`/`Program::linearize` bounds at their construction sites, so the dispatcher itself only
        // supplies the zero provider those rules use to materialize structural zeros.
        where_clause.predicates.push(syn::parse_quote! {
            #differentiation_self_type: #ryft::ZeroOperationProvider<#primary_type>
        });

        let jvp_arms = variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            let operation_type = &variant.program_payload_type;
            let receiver = variant.receiver();
            match &variant.class {
                OperationVariantClass::CompositeNative => quote! {
                    Self::#variant_ident(operation) => {
                        <#operation_type as #ryft::DifferentiableOperation<__DifferentiationContext>>::jvp(
                            #receiver,
                            context,
                            driver,
                            inputs,
                        )
                    },
                },
                OperationVariantClass::ProjectedMember { structural: false, .. }
                | OperationVariantClass::MixedMember { structural: false, .. } => quote! {
                    Self::#variant_ident(operation) => {
                        <#operation_type as #ryft::MemberDifferentiableOperation<__DifferentiationContext>>::
                            jvp_in_parent(#receiver, context, driver, inputs)
                    },
                },
                // A structural mixed payload is constant with respect to its parent-universe operands, but its zero
                // tangent still needs the runtime geometry those operands carry. Stage the primal and the member zero
                // over the same operands so the geometry stays available to both. Each output's zero tangent is staged
                // in the computational member universe that output belongs to, and an output outside every such
                // universe (e.g., a structural member output) has a zero differential space and needs no instruction.
                OperationVariantClass::MixedMember { member_type, structural: true } => {
                    let tangent_universe_arms = self.tangent_universes(member_type).into_iter().map(|member_type| {
                        quote! {
                            if let ::std::result::Result::Ok(output_type) =
                                <&#member_type as ::std::convert::TryFrom<&#primary_type>>::try_from(&output_type)
                            {
                                let tangent_type =
                                    <#member_type as #ryft::DifferentiableType>::tangent(output_type)?;
                                let mut tangents = context.bind(
                                    <#differentiation_self_type as ::std::convert::From<
                                        #ryft::ZeroOperation<#member_type>,
                                    >>::from(#ryft::ZeroOperation::new(tangent_type)),
                                    ::std::vec::Vec::new(),
                                    primal_inputs.as_slice(),
                                )?;
                                #ryft::check_count!("output", tangents, 1, ProgramError);
                                return #ryft::DifferentiationDual::new(
                                    primal,
                                    #ryft::MaybeZero::Value(tangents.remove(0)),
                                )
                                .map_err(::std::convert::Into::into);
                            }
                        }
                    });
                    quote! {
                        Self::#variant_ident(operation) => {
                            let primal_inputs = inputs
                                .iter()
                                .map(|input| input.primal().clone())
                                .collect::<::std::vec::Vec<_>>();
                            let input_types = primal_inputs
                                .iter()
                                .map(|input| #ryft::Typed::r#type(input).into_owned())
                                .collect::<::std::vec::Vec<_>>();
                            let output_types = <#operation_type as #ryft::MemberOperation<#primary_type>>::
                                infer_parent_output_types(#receiver, input_types.as_slice(), &[])?;
                            let primals =
                                context.bind(self.clone(), ::std::vec::Vec::new(), primal_inputs.as_slice())?;
                            #ryft::check_count!("output", primals, output_types.len(), ProgramError);
                            primals
                                .into_iter()
                                .zip(output_types)
                                .map(|(primal, output_type)| {
                                    #(#tangent_universe_arms)*
                                    #ryft::DifferentiationDual::new_with_zero_tangent(primal)
                                })
                                .collect()
                        },
                    }
                }
                OperationVariantClass::ProjectedMember { structural: true, .. } => quote! {
                    Self::#variant_ident(_) => {
                        context
                            .bind(
                                self.clone(),
                                ::std::vec::Vec::new(),
                                &inputs
                                    .iter()
                                    .map(|input| input.primal().clone())
                                    .collect::<::std::vec::Vec<_>>(),
                            )?
                            .into_iter()
                            .map(#ryft::DifferentiationDual::new_with_zero_tangent)
                            .collect()
                    },
                },
            }
        });
        let (differentiation_impl_generics, _, differentiation_where_clause) =
            differentiation_generics.split_for_impl();

        const_block(quote! {
            #[automatically_derived]
            impl #differentiation_impl_generics
                #ryft::DifferentiableOperation<__DifferentiationContext>
                for #differentiation_self_type
            #differentiation_where_clause
            {
                fn jvp<__D: #ryft::DifferentiationDriver<__DifferentiationContext>>(
                    &self,
                    context: &__DifferentiationContext,
                    driver: &__D,
                    inputs: &[#ryft::DifferentiationDual<
                        <__DifferentiationContext as #ryft::Domain>::Value,
                    >],
                ) -> ::std::result::Result<
                    ::std::vec::Vec<#ryft::DifferentiationDual<
                        <__DifferentiationContext as #ryft::Domain>::Value,
                    >>,
                    #ryft::DifferentiationError,
                > {
                    match self {
                        #(#jvp_arms)*
                    }
                }
            }
        })
    }

    /// Generates the `TransposableOperation` dispatcher. Enums with one inferred constant-value parameter or an
    /// explicit operation-family declaration transpose over a separate generated `__TranspositionValue` parameter.
    /// Enums with two or more inferred value parameters pin the transposition value to the first (tangent/cotangent)
    /// value parameter. Higher-order rules request nested-program transposition through their instruction-scoped
    /// driver, whose concrete implementation establishes the corresponding `Program::transpose_with_respect_to`
    /// bounds.
    fn generate_transposable_operation(&self) -> TokenStream {
        let variants = &self.variants;
        let ryft = &self.ryft_crate;
        let primary_type = &self.operation_type;

        let operation_self_type = &self.self_type;
        let program_constant_type = &self.program_constant_type;
        let has_separate_transposition_value_type = self.has_separate_runtime_value_type;
        let transposed_value_type: syn::Type = if has_separate_transposition_value_type {
            syn::parse_quote!(__TranspositionValue)
        } else {
            syn::parse_quote!(#program_constant_type)
        };
        let mut transposition_generics = self.operation_generics.clone();
        if has_separate_transposition_value_type {
            transposition_generics.params.push(syn::parse_quote!(__TranspositionValue));
        }

        let where_clause = transposition_generics.make_where_clause();
        if has_separate_transposition_value_type {
            where_clause
                .predicates
                .push(syn::parse_quote!(#transposed_value_type: #ryft::Value<Type = #primary_type>));
            if let Some(program_constant_parameter) = &self.program_constant_parameter {
                where_clause.predicates.extend(generic_parameter_bounds_as_predicates(
                    &self.generics,
                    program_constant_parameter,
                    &transposed_value_type,
                ));
            }
        }
        where_clause
            .predicates
            .push(syn::parse_quote!(#operation_self_type: #ryft::Operation<Type = #primary_type>));
        for variant in variants {
            let operation_type = &variant.payload_type;
            match &variant.class {
                OperationVariantClass::CompositeNative => where_clause.predicates.push(syn::parse_quote! {
                    #operation_type: #ryft::TransposableOperation<
                        #transposed_value_type,
                        #operation_self_type,
                    >
                }),
                OperationVariantClass::MixedMember { member_type, .. } => {
                    where_clause.predicates.push(syn::parse_quote! {
                        #member_type: #ryft::DifferentiableType
                    });
                    where_clause.predicates.push(syn::parse_quote! {
                        #transposed_value_type: #ryft::ValueProjection<
                            #member_type,
                            Projected: #ryft::Value<Type = #member_type>,
                        >
                    });
                    where_clause.predicates.push(syn::parse_quote! {
                        #operation_self_type: #ryft::OperationProjection<#member_type>
                    });
                    where_clause.predicates.push(syn::parse_quote! {
                        <#operation_self_type as #ryft::OperationProjection<#member_type>>::Projected:
                            ::std::convert::From<#operation_type>
                                + #ryft::TransposableOperation<
                                    <#transposed_value_type as #ryft::ValueProjection<#member_type>>::Projected,
                                    <#operation_self_type as #ryft::OperationProjection<#member_type>>::Projected,
                                >
                    });
                    where_clause.predicates.push(syn::parse_quote! {
                        #primary_type: ::std::convert::From<#member_type>
                    });
                    where_clause.predicates.push(syn::parse_quote! {
                        for<'__t> &'__t #member_type:
                            ::std::convert::TryFrom<&'__t #primary_type, Error = #ryft::TypeError>
                    });
                }
                OperationVariantClass::ProjectedMember { member_type, structural: false } => {
                    where_clause.predicates.push(syn::parse_quote! {
                        #transposed_value_type: #ryft::ValueProjection<
                            #member_type,
                            Projected: #ryft::Value<Type = #member_type>,
                        >
                    });
                    where_clause.predicates.push(syn::parse_quote! {
                        #operation_self_type: #ryft::OperationProjection<
                            #member_type,
                            Projected = #operation_type,
                        >
                    });
                    where_clause.predicates.push(syn::parse_quote! {
                        #operation_type: #ryft::TransposableOperation<
                            <#transposed_value_type as #ryft::ValueProjection<#member_type>>::Projected,
                            #operation_type,
                        >
                    });
                }
                OperationVariantClass::ProjectedMember { structural: true, .. } => {}
            }
        }

        let (transposition_impl_generics, _, transposition_where_clause) = transposition_generics.split_for_impl();
        let transpose_arms = variants.iter().map(|variant| {
            let variant_ident = &variant.ident;
            let operation_type = &variant.payload_type;
            let receiver = variant.receiver();
            match &variant.class {
                OperationVariantClass::CompositeNative => quote! {
                    Self::#variant_ident(operation) => {
                        <#operation_type as #ryft::TransposableOperation<
                            #transposed_value_type,
                            #operation_self_type,
                        >>::transpose(#receiver, context, driver, inputs, outputs)
                    },
                },
                OperationVariantClass::MixedMember { .. } => quote! {
                    Self::#variant_ident(operation) => {
                        #ryft::transpose_mixed_operation(context, #receiver, inputs, outputs)
                    },
                },
                OperationVariantClass::ProjectedMember { structural: false, .. } => quote! {
                    Self::#variant_ident(operation) => {
                        #ryft::transpose_projected_operation(context, #receiver, inputs, outputs)
                    },
                },
                OperationVariantClass::ProjectedMember { structural: true, .. } => quote! {
                    Self::#variant_ident(_) => {
                        inputs
                            .iter()
                            .map(|input| {
                                ::std::result::Result::Ok(#ryft::MaybeZero::Zero(input.r#type().cotangent()?))
                            })
                            .collect()
                    },
                },
            }
        });

        const_block(quote! {
            #[automatically_derived]
            impl #transposition_impl_generics
                #ryft::TransposableOperation<#transposed_value_type, #operation_self_type>
                for #operation_self_type
            #transposition_where_clause
            {
                fn transpose<__D: #ryft::TranspositionDriver<
                    #transposed_value_type,
                    #operation_self_type,
                >>(
                    &self,
                    context: &mut #ryft::TracingContext<
                        #transposed_value_type,
                        #operation_self_type,
                    >,
                    driver: &__D,
                    inputs: &[#ryft::PartialValue<
                        #ryft::Tracer<#ryft::TracingContext<
                            #transposed_value_type,
                            #operation_self_type,
                        >>,
                    >],
                    outputs: &[#ryft::MaybeZero<
                        #ryft::Tracer<#ryft::TracingContext<
                            #transposed_value_type,
                            #operation_self_type,
                        >>,
                    >],
                ) -> ::std::result::Result<
                    ::std::vec::Vec<#ryft::MaybeZero<
                        #ryft::Tracer<#ryft::TracingContext<
                            #transposed_value_type,
                            #operation_self_type,
                        >>,
                    >>,
                    #ryft::DifferentiationError,
                > {
                    match self {
                        #(#transpose_arms)*
                    }
                }
            }
        })
    }

    /// Generates the `From<Payload>` and borrowed `TryFrom<&Enum>` conversion implementations for one
    /// conversion-enabled variant. Boxed payloads box the payload in `From` and deref through the box in `TryFrom`.
    /// The borrowed projection fails with a [`TypeError`](ryft_core::TypeError) naming both the operation that was
    /// projected and the payload the caller expected, so the enum requires [`Operation`](ryft_core::Operation) to
    /// render that diagnostic.
    fn generate_conversion_impl(&self, variant: &OperationVariant) -> TokenStream {
        let generics = &self.conversion_generics;
        let ryft = &self.ryft_crate;
        let enum_ident = &self.ident;
        let enum_type = &self.self_type;
        let (impl_generics, _, where_clause) = generics.split_for_impl();
        let variant_ident = &variant.ident;
        let operation_type = &variant.payload_type;
        let payload_name = operation_type.to_token_stream().to_string().replace(' ', "");
        let mut try_from_generics = generics.clone();
        try_from_generics
            .params
            .insert(0, syn::GenericParam::Lifetime(syn::LifetimeParam::new(syn::parse_quote!('__operation))));
        try_from_generics
            .make_where_clause()
            .predicates
            .push(syn::parse_quote!(#enum_type: #ryft::Operation));
        let (try_from_impl_generics, _, try_from_where_clause) = try_from_generics.split_for_impl();

        let from_body = if variant.is_boxed {
            quote!(Self::#variant_ident(::std::boxed::Box::new(operation)))
        } else {
            quote!(Self::#variant_ident(operation))
        };
        let try_from_body = if variant.is_boxed { quote!(Ok(&**operation)) } else { quote!(Ok(operation)) };

        let from_impl = variant.generate_from.then(|| {
            quote! {
                #[automatically_derived]
                impl #impl_generics ::std::convert::From<#operation_type> for #enum_type
                #where_clause
                {
                    fn from(operation: #operation_type) -> Self {
                        #from_body
                    }
                }
            }
        });

        quote! {
            #from_impl

            #[automatically_derived]
            impl #try_from_impl_generics ::std::convert::TryFrom<&'__operation #enum_type>
                for &'__operation #operation_type
            #try_from_where_clause
            {
                type Error = #ryft::TypeError;

                fn try_from(
                    value: &'__operation #enum_type,
                ) -> ::std::result::Result<Self, #ryft::TypeError> {
                    match value {
                        #enum_ident::#variant_ident(operation) => #try_from_body,
                        _ => Err(#ryft::TypeError::invalid(::std::format!(
                            "cannot project operation '{}' into a '{}' payload",
                            <#enum_type as #ryft::Operation>::name(value),
                            #payload_name,
                        ))),
                    }
                }
            }
        }
    }

    /// Generates the canonical [`OperationProjection`] implementation for one declared projected member variant, in
    /// either role. Composite-native and mixed variants do not define homogeneous operation-family projections.
    fn generate_operation_projection_impl(&self, variant: &OperationVariant) -> Option<TokenStream> {
        let member_type = variant.class.projected_member_type()?;
        let ryft = &self.ryft_crate;
        let enum_type = &self.self_type;
        let projected_type = &variant.payload_type;
        let generics = &self.operation_generics;
        let (impl_generics, _, where_clause) = generics.split_for_impl();
        Some(quote! {
            #[automatically_derived]
            impl #impl_generics #ryft::OperationProjection<#member_type> for #enum_type
            #where_clause
            {
                type Projected = #projected_type;
            }
        })
    }
    /// Builds the generics for the generated [`InterpretableOperation`] dispatcher: the enum generics with
    /// program-shaped value substitutions applied, one generated `__Context` parameter, the context's [`Domain`]
    /// equalities, the constant-lifting `Constant` context bound, and one `InterpretableOperation` predicate per
    /// payload.
    fn interpretation_generics(&self) -> syn::Generics {
        let ryft = &self.ryft_crate;
        let primary_type = &self.operation_type;
        let program_constant_type = &self.program_constant_type;
        let has_separate_interpretation_value_type = self.has_separate_runtime_value_type;
        let interpretation_value_type: syn::Type = syn::parse_quote!(<__Context as #ryft::Domain>::Value);
        let mut generics = self.program_generics.clone();
        generics.params.push(syn::parse_quote!(__Context));
        let where_clause = generics.make_where_clause();
        let mut domain_bound: syn::TypeParamBound = syn::parse_quote!(#ryft::Domain<Type = #primary_type>);
        if !has_separate_interpretation_value_type {
            domain_bound = syn::parse_quote! {
                #ryft::Domain<
                    Type = #primary_type,
                    Value = #program_constant_type,
                >
            };
        }
        where_clause.predicates.push(syn::parse_quote!(__Context: #domain_bound));
        if has_separate_interpretation_value_type {
            if let Some(program_constant_parameter) = &self.program_constant_parameter {
                where_clause.predicates.extend(generic_parameter_bounds_as_predicates(
                    &self.generics,
                    program_constant_parameter,
                    &interpretation_value_type,
                ));
            }
            where_clause.predicates.push(syn::parse_quote! {
                __Context: #ryft::Constant<
                    #interpretation_value_type,
                    #program_constant_type,
                >
            });
        }
        for variant in &self.variants {
            let operation_type = &variant.program_payload_type;
            match &variant.class {
                OperationVariantClass::CompositeNative => where_clause.predicates.push(syn::parse_quote! {
                    #operation_type: #ryft::InterpretableOperation<__Context>
                }),
                OperationVariantClass::MixedMember { .. } => where_clause.predicates.push(syn::parse_quote! {
                    #operation_type: #ryft::MemberInterpretableOperation<__Context>
                }),
                OperationVariantClass::ProjectedMember { .. } => {}
            }
        }
        for (variant, member_type) in self
            .variants
            .iter()
            .filter_map(|variant| variant.class.projected_member_type().map(|r#type| (variant, r#type)))
        {
            let operation_type = &variant.program_payload_type;
            where_clause.predicates.push(syn::parse_quote! {
                <__Context as #ryft::Domain>::Value: #ryft::ValueProjection<
                    #member_type,
                    Projected: #ryft::Value<Type = #member_type>,
                >
            });
            where_clause.predicates.push(syn::parse_quote! {
                #operation_type: #ryft::InterpretableOperation<#ryft::EagerContext<
                    <<__Context as #ryft::Domain>::Value as #ryft::ValueProjection<#member_type>>::Projected,
                    #operation_type,
                >>
            });
        }
        generics
    }
}

/// Operation enum variant extracted from the derive input, together with the payload metadata that drives the
/// generated dispatch arms, predicates, and conversions.
struct OperationVariant {
    /// Semantic dispatch class of this variant.
    class: OperationVariantClass,

    /// Identifier of the enum variant.
    ident: syn::Ident,

    /// Operation type exposed by generated conversions.
    payload_type: syn::Type,

    /// Operation type used by generated program-shaped semantic implementations.
    program_payload_type: syn::Type,

    /// Whether the stored payload is `Box<operation_type>`.
    is_boxed: bool,

    /// Whether this variant stores a bare generic extension payload.
    is_generic_extension: bool,

    /// Whether to generate the direct `From<Payload>` conversion for this variant.
    generate_from: bool,
}

/// Semantic dispatch class declared for one operation enum variant, factored as a boundary shape (how the payload's
/// type boundary relates to the enclosing universe) crossed with a transform role (whether the payload carries real
/// transform rules or is transform-inert). Both member boundaries share the `class(U [, structural])` grammar, so the
/// role rides each boundary as a flag instead of splitting one boundary into two class names.
enum OperationVariantClass {
    /// Operation whose payload already uses the enclosing operation family's type and semantic contracts.
    CompositeNative,

    /// Homogeneous member whose inference, execution, and transform rules run in a projected context.
    ProjectedMember {
        /// Type of the projected member universe.
        member_type: syn::Type,

        /// Whether this payload is transform-inert. A structural projected member has nothing to differentiate and
        /// nothing to batch per item, so forward mode stages a zero tangent and transposition returns zero cotangents
        /// instead of consulting a payload rule.
        structural: bool,
    },

    /// Native member payload whose parent instruction has a genuinely mixed boundary.
    MixedMember {
        /// Type of the member universe the payload keeps natively.
        member_type: syn::Type,

        /// Whether this payload is transform-inert, so that forward mode stages a zero tangent instead of consulting a
        /// payload rule.
        structural: bool,
    },
}

impl OperationVariantClass {
    /// Returns the marker name that declares this member class.
    fn name(&self) -> &'static str {
        match self {
            Self::CompositeNative => unreachable!("composite-native variants have no class marker"),
            Self::ProjectedMember { .. } => "projected",
            Self::MixedMember { .. } => "mixed",
        }
    }

    /// Returns the operation type required of this variant's payload, or [`None`] when a mixed member instead uses
    /// [`MemberOperation`](ryft_core::MemberOperation) for its parent boundary.
    fn operation_type<'t>(&'t self, primary_type: &'t syn::Type) -> Option<&'t syn::Type> {
        match self {
            Self::CompositeNative => Some(primary_type),
            Self::MixedMember { .. } => None,
            Self::ProjectedMember { member_type, .. } => Some(member_type),
        }
    }

    /// Returns the projected-boundary member type this variant claims as the enclosing family's canonical
    /// [`OperationProjection`](ryft_core::OperationProjection) target, or [`None`] for composite-native and mixed
    /// variants. A mixed variant keeps a native member type without owning that projection, so its dispatchers read it
    /// directly off [`Self::MixedMember`].
    fn projected_member_type(&self) -> Option<&syn::Type> {
        match self {
            Self::CompositeNative | Self::MixedMember { .. } => None,
            Self::ProjectedMember { member_type, .. } => Some(member_type),
        }
    }

    /// Applies program-value substitutions to the declared member type.
    fn substitute_type_idents(&mut self, substitutions: &[(syn::Ident, syn::Type)]) {
        match self {
            Self::CompositeNative => {}
            Self::ProjectedMember { member_type, .. } | Self::MixedMember { member_type, .. } => {
                *member_type = substitute_type_idents(member_type, substitutions);
            }
        }
    }
}

impl OperationVariant {
    /// Receiver expression to use when delegating to the wrapped operation.
    fn receiver(&self) -> TokenStream {
        if self.is_boxed { quote!(&**operation) } else { quote!(operation) }
    }
}

/// Builds the generics used by the generated [`Operation`] and [`Display`] implementations: the enum generics
/// without defaults, plus one payload predicate per distinct contract. Composite-native variants use the enclosing
/// family's primary type, declared projected variants use their member type, and mixed members use
/// [`MemberOperation`](ryft_core::MemberOperation) for their parent boundary.
fn operation_generics(
    generics: &syn::Generics,
    variants: &[OperationVariant],
    ryft: &syn::Path,
    operation_type: &syn::Type,
) -> syn::Generics {
    let mut generics = generics.without_defaults();
    let mut seen_payload_contracts = std::collections::HashSet::new();
    let payload_operation_bounds = variants.iter().filter_map(|variant| {
        let expected_type = variant.class.operation_type(operation_type);
        let contract = expected_type
            .map(ToTokens::to_token_stream)
            .unwrap_or_else(|| quote!(#ryft::MemberOperation<#operation_type>))
            .to_string();
        if !seen_payload_contracts.insert((variant.payload_type.to_token_stream().to_string(), contract)) {
            return None;
        }
        Some::<syn::WherePredicate>(match expected_type {
            Some(expected_type) => {
                let payload_type = &variant.payload_type;
                syn::parse_quote!(#payload_type: #ryft::Operation<Type = #expected_type>)
            }
            None => {
                let payload_type = &variant.payload_type;
                syn::parse_quote!(#payload_type: #ryft::MemberOperation<#operation_type>)
            }
        })
    });
    generics.make_where_clause().predicates.extend(payload_operation_bounds);
    let mut seen_member_types = std::collections::HashSet::new();
    for member_type in variants
        .iter()
        .filter_map(|variant| variant.class.projected_member_type())
        .filter(|member_type| seen_member_types.insert(member_type.to_token_stream().to_string()))
    {
        let where_clause = generics.make_where_clause();
        where_clause.predicates.push(syn::parse_quote! {
            #member_type: #ryft::Type<
                Identity = <#operation_type as #ryft::Type>::Identity,
            >
        });
        where_clause.predicates.push(syn::parse_quote!(#operation_type: ::std::convert::From<#member_type>));
        where_clause.predicates.push(syn::parse_quote! {
            for<'__member_type> &'__member_type #member_type: ::std::convert::TryFrom<
                &'__member_type #operation_type,
                Error = #ryft::TypeError,
            >
        });
    }
    generics
}

/// Returns the inner type of a `Box<T>` type expression. This recognizes any type-path whose final path segment is
/// `Box` with exactly one type argument and returns that type argument, returning [`None`] for any other type.
fn boxed_inner_type(ty: &syn::Type) -> Option<syn::Type> {
    let syn::Type::Path(type_path) = ty else {
        return None;
    };
    if type_path.qself.is_some() {
        return None;
    }
    let segment = type_path.path.segments.last()?;
    if segment.ident != "Box" {
        return None;
    }
    let syn::PathArguments::AngleBracketed(arguments) = &segment.arguments else {
        return None;
    };
    if arguments.args.len() != 1 {
        return None;
    }
    match arguments.args.first() {
        Some(syn::GenericArgument::Type(inner_type)) => Some(inner_type.clone()),
        _ => None,
    }
}

/// Returns whether `ty` is exactly a bare enum type parameter (e.g., the `Extension` payload of an
/// `Extension(Extension)` variant). Bare generic payloads are the ones whose generated conversions must be skipped,
/// because a `From<Extension>` implementation would overlap with the concrete payload conversions whenever
/// `Extension` is instantiated as one of the concrete payload types.
fn is_bare_generic_parameter(ty: &syn::Type, generics: &syn::Generics) -> bool {
    let syn::Type::Path(type_path) = ty else {
        return false;
    };
    if type_path.qself.is_some() || type_path.path.segments.len() != 1 {
        return false;
    }
    let Some(segment) = type_path.path.segments.first() else {
        return false;
    };
    if !matches!(segment.arguments, syn::PathArguments::None) {
        return false;
    }
    generics.type_params().any(|parameter| parameter.ident == segment.ident)
}

/// Returns whether `ty` is exactly the provided identifier.
fn type_is_ident(ty: &syn::Type, ident: &syn::Ident) -> bool {
    matches!(ty, syn::Type::Path(syn::TypePath { qself: None, path }) if path.is_ident(ident))
}

/// Returns whether `ty` mentions the provided identifier anywhere in its structure (as a bare path segment or nested
/// inside array, function, group, parenthesized, pointer, reference, slice, tuple, or generic-argument positions).
fn type_mentions_ident(ty: &syn::Type, ident: &syn::Ident) -> bool {
    match ty {
        syn::Type::Array(ty) => type_mentions_ident(&ty.elem, ident),
        syn::Type::BareFn(ty) => {
            ty.inputs.iter().any(|input| type_mentions_ident(&input.ty, ident))
                || match &ty.output {
                    syn::ReturnType::Default => false,
                    syn::ReturnType::Type(_, ty) => type_mentions_ident(ty, ident),
                }
        }
        syn::Type::Group(ty) => type_mentions_ident(&ty.elem, ident),
        syn::Type::Paren(ty) => type_mentions_ident(&ty.elem, ident),
        syn::Type::Path(ty) => {
            ty.qself.as_ref().is_some_and(|qself| type_mentions_ident(&qself.ty, ident))
                || ty.path.segments.iter().any(|segment| {
                    segment.ident == *ident
                        || match &segment.arguments {
                            syn::PathArguments::None => false,
                            syn::PathArguments::AngleBracketed(arguments) => arguments.args.iter().any(|argument| {
                                matches!(
                                    argument,
                                    syn::GenericArgument::Type(ty) if type_mentions_ident(ty, ident)
                                ) || matches!(
                                    argument,
                                    syn::GenericArgument::AssocType(argument)
                                        if type_mentions_ident(&argument.ty, ident)
                                )
                            }),
                            syn::PathArguments::Parenthesized(arguments) => {
                                arguments.inputs.iter().any(|ty| type_mentions_ident(ty, ident))
                                    || match &arguments.output {
                                        syn::ReturnType::Default => false,
                                        syn::ReturnType::Type(_, ty) => type_mentions_ident(ty, ident),
                                    }
                            }
                        }
                })
        }
        syn::Type::Ptr(ty) => type_mentions_ident(&ty.elem, ident),
        syn::Type::Reference(ty) => type_mentions_ident(&ty.elem, ident),
        syn::Type::Slice(ty) => type_mentions_ident(&ty.elem, ident),
        syn::Type::Tuple(ty) => ty.elems.iter().any(|ty| type_mentions_ident(ty, ident)),
        _ => false,
    }
}

/// Substitutes bare type identifiers in `ty` according to the provided substitutions, returning the substituted
/// type. Refer to the documentation of [`TypeIdentSubstituter`] for information on which mentions are substituted.
fn substitute_type_idents(ty: &syn::Type, substitutions: &[(syn::Ident, syn::Type)]) -> syn::Type {
    let mut ty = ty.clone();
    TypeIdentSubstituter { substitutions }.visit_type_mut(&mut ty);
    ty
}

/// Substitutes bare type identifiers in `generics` according to the provided substitutions and removes the
/// substituted type parameters from the parameter list (they are replaced by concrete types and must not remain
/// generic in the generated implementations).
fn substitute_generics(generics: &syn::Generics, substitutions: &[(syn::Ident, syn::Type)]) -> syn::Generics {
    let mut generics = generics.clone();
    generics.params = generics
        .params
        .into_iter()
        .filter(|parameter| {
            !matches!(
                parameter,
                syn::GenericParam::Type(parameter)
                    if substitutions.iter().any(|(ident, _)| parameter.ident == *ident)
            )
        })
        .collect();
    TypeIdentSubstituter { substitutions }.visit_generics_mut(&mut generics);
    generics
}

/// Copies the declared bounds of the `source` generic parameter (both inline bounds and where-clause predicates
/// mentioning it) onto the generated `target` type, so that a generated value parameter inherits the same
/// capability requirements that the enum declares for its own value parameter.
///
/// # Parameters
///
///   - `generics`: Enum generics declaring the `source` parameter.
///   - `source`: Enum value parameter whose bounds are copied.
///   - `target`: Generated type that receives the copied bounds.
fn generic_parameter_bounds_as_predicates(
    generics: &syn::Generics,
    source: &syn::Ident,
    target: &syn::Type,
) -> Vec<syn::WherePredicate> {
    let mut predicates = generics
        .type_params()
        .find(|parameter| parameter.ident == *source)
        .into_iter()
        .flat_map(|parameter| parameter.bounds.iter())
        .map(|bound| syn::parse_quote!(#target: #bound))
        .collect::<Vec<syn::WherePredicate>>();
    if let Some(where_clause) = &generics.where_clause {
        predicates.extend(where_clause.predicates.iter().filter_map(|predicate| match predicate {
            syn::WherePredicate::Type(predicate) if type_mentions_ident(&predicate.bounded_ty, source) => {
                let mut predicate = syn::WherePredicate::Type(predicate.clone());
                TypeIdentSubstituter { substitutions: &[(source.clone(), target.clone())] }
                    .visit_where_predicate_mut(&mut predicate);
                Some(predicate)
            }
            _ => None,
        }));
    }
    predicates
}

/// [`VisitMut`] visitor that replaces bare type identifier mentions with concrete replacement types: a
/// single-segment argument-free path is replaced wholesale, while a multi-segment path whose first segment matches a
/// substituted identifier has that first segment replaced by the replacement path (preserving the remaining
/// segments), so that associated-type projections through a substituted parameter keep working.
struct TypeIdentSubstituter<'a> {
    /// Type identifier substitutions.
    substitutions: &'a [(syn::Ident, syn::Type)],
}

impl VisitMut for TypeIdentSubstituter<'_> {
    fn visit_type_mut(&mut self, ty: &mut syn::Type) {
        if let syn::Type::Path(type_path) = ty
            && type_path.qself.is_none()
        {
            if type_path.path.segments.len() == 1
                && let Some(segment) = type_path.path.segments.first()
                && matches!(segment.arguments, syn::PathArguments::None)
                && let Some((_, replacement)) = self.substitutions.iter().find(|(ident, _)| segment.ident == *ident)
            {
                *ty = replacement.clone();
                return;
            }
            if let Some(first_segment) = type_path.path.segments.first()
                && matches!(first_segment.arguments, syn::PathArguments::None)
                && let Some((_, syn::Type::Path(replacement))) =
                    self.substitutions.iter().find(|(ident, _)| first_segment.ident == *ident)
                && replacement.qself.is_none()
            {
                let remaining_segments = type_path.path.segments.iter().skip(1).cloned();
                type_path.path.leading_colon = replacement.path.leading_colon;
                type_path.path.segments = replacement.path.segments.iter().cloned().chain(remaining_segments).collect();
            }
        }
        syn::visit_mut::visit_type_mut(self, ty);
    }
}

/// Builds the program-shaped value substitutions for the provided value type parameters: every value parameter
/// after the first two is substituted with the program constant type (the first value parameter). The first value
/// parameter is the program-constant/flowing value space and the second is the capture/constant space, while later
/// value parameters are payload-specific metadata that program-shaped implementations (which have one value space)
/// must pin to the program constant type. Refer to the documentation of the [`Operation`] trait for information on
/// how the value types of generated implementations are inferred.
fn program_value_substitutions(
    value_type_parameters: &[syn::Ident],
    program_constant_type: &syn::Ident,
) -> Vec<(syn::Ident, syn::Type)> {
    value_type_parameters
        .iter()
        .skip(2)
        .cloned()
        .map(|parameter| {
            let replacement: syn::Type = syn::parse_quote!(#program_constant_type);
            (parameter, replacement)
        })
        .collect()
}

/// Returns generic value parameters bounded by `Value<Type = operation_type>`.
fn value_type_parameters(generics: &syn::Generics, operation_type: &syn::Type) -> Vec<syn::Ident> {
    generics
        .type_params()
        .filter(|parameter| {
            parameter.bounds.iter().any(|bound| {
                value_bound_argument(bound).is_some_and(|argument| type_tokens_equal(&argument, operation_type))
            }) || generics.where_clause.iter().any(|where_clause| {
                where_clause.predicates.iter().any(|predicate| match predicate {
                    syn::WherePredicate::Type(predicate) if type_is_ident(&predicate.bounded_ty, &parameter.ident) => {
                        predicate.bounds.iter().any(|bound| {
                            value_bound_argument(bound)
                                .is_some_and(|argument| type_tokens_equal(&argument, operation_type))
                        })
                    }
                    _ => false,
                })
            })
        })
        .map(|parameter| parameter.ident.clone())
        .collect()
}

/// Returns whether two types have the same token representation. Given that procedural macros are executed before
/// type checking and inference is performed by the Rust compiler, token equality is the strongest type equality we
/// can check for here (e.g., type aliases cannot be resolved).
fn type_tokens_equal(left: &syn::Type, right: &syn::Type) -> bool {
    left.to_token_stream().to_string().replace(' ', "") == right.to_token_stream().to_string().replace(' ', "")
}

/// Extracts distinct `Value<Type = T>` bound arguments from `generics`, preserving their first-seen order.
fn unique_value_bound_arguments(generics: &syn::Generics) -> Vec<syn::Type> {
    value_bound_arguments(generics).into_iter().fold(Vec::new(), |mut arguments, argument| {
        if arguments.iter().all(|existing_argument| !type_tokens_equal(existing_argument, &argument)) {
            arguments.push(argument);
        }
        arguments
    })
}

/// Extracts all `Value<Type = T>` bound arguments from `generics`.
fn value_bound_arguments(generics: &syn::Generics) -> Vec<syn::Type> {
    let parameter_bounds = generics.type_params().flat_map(|parameter| parameter.bounds.iter());
    let where_bounds = generics
        .where_clause
        .iter()
        .flat_map(|where_clause| where_clause.predicates.iter())
        .filter_map(|predicate| match predicate {
            syn::WherePredicate::Type(predicate) => Some(predicate.bounds.iter()),
            _ => None,
        })
        .flatten();

    parameter_bounds.chain(where_bounds).filter_map(value_bound_argument).collect()
}

/// Returns the bound `Type` from a `Value<Type = T>` trait bound.
fn value_bound_argument(bound: &syn::TypeParamBound) -> Option<syn::Type> {
    let syn::TypeParamBound::Trait(bound) = bound else {
        return None;
    };
    let segment = bound.path.segments.last()?;
    if segment.ident != "Value" {
        return None;
    }
    let syn::PathArguments::AngleBracketed(arguments) = &segment.arguments else {
        return None;
    };
    match arguments.args.first() {
        Some(syn::GenericArgument::AssocType(binding)) if arguments.args.len() == 1 && binding.ident == "Type" => {
            Some(binding.ty.clone())
        }
        _ => None,
    }
}

